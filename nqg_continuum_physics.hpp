struct HydroResult {
  Vec3 force = Vec3(0, 0, 0);
  Vec3 dragCoeff = Vec3(0, 0, 0);
  Vec3 waterVel = Vec3(0, 0, 0);
  real submergedVolume = 0;
  real submergedFraction = 0;
  real addedMass = 0;
  real buoyancy = 0;
  real squeeze = 0;
  real level = 0;
  real film = 0;
  real bedZ = 0;
  Vec3 centroid = Vec3(0, 0, 0); // baricentro del volume immerso (spinta)
  bool wet = false;
};

class ContinuousWaterBody {
public:
  fluid::ShallowFlow flow;

  real refractiveIndex = 1.333;
  // Coefficienti di assorbimento dell'acqua pura (Pope & Fry 1997) a ~610,
  // ~550, ~460 nm [1/m].
  Vec3 absorptionCoeff = Vec3(0.30, 0.064, 0.010);
  real bodyContactAngle = 1.1;
  real addedMassCoeffBox = 0.6;
  real addedMassCoeffSphere = 0.5;
  real addedMassCoeffCylinder = 0.8; // flusso trasversale (cilindro/capsula)
  // Scabrezza delle superfici a contatto: sotto questa distanza l'acqua
  // sotto il corpo drena attraverso le asperita' e non c'e' piu' squeeze-film.
  // (= scala di scabrezza del fondo, la stessa della ritenzione del film)
  real asperityGap = fluid::ROUGHNESS;

  // Quota del terreno SENZA i corpi (serve ai corpi appoggiati sul fondo).
  std::function<real(real, real)> terrainFn;
  real terrainAt(real x, real y) const {
    return terrainFn ? terrainFn(x, y) : flow.bedAt(x, y);
  }

  Vec3 basinCenter = Vec3(0, 0, 0);
  real waterVolume = 0.0;     // acqua reale (netta del volume spostato)
  real displacedVolume = 0.0; // volume dei corpi immersi iniettato nell'anello
  real simTime_ = 0.0;

  ContinuousWaterBody() : flow(0.1, 128, 128, 0.0, 0.0) {}

  void setBedProvider(fluid::ShallowFlow::BedFn fn) {
    flow.bed = std::move(fn);
  }
  void refreshBed() { flow.refreshBed(); }
  void setLiquidTemperature(real kelvin) {
    const real angle = flow.liquid.contactAngle;
    flow.liquid = fluid::waterAtKelvin(kelvin);
    flow.liquid.contactAngle = angle;
  }
  void setContactAngle(real radians) { flow.liquid.contactAngle = radians; }
  void setWind(const Vec3 &w) {
    flow.windX = w.x;
    flow.windY = w.y;
  }
  void setGravity(real g) { flow.gravity = std::max(1e-3, g); }

  void step(real dt) {
    flow.step(dt);
    updateVolume();
    simTime_ += dt;
  }
  void clear() {
    flow.clear();
    waterVolume = 0.0;
    displacedVolume = 0.0;
    simTime_ = 0.0;
  }
  void initialFill(real xa, real xb, real ya, real yb, real depth) {
    flow.fillRect(xa, xb, ya, yb, depth);
    updateVolume();
  }
  void initialFillVolume(real xa, real xb, real ya, real yb, real volume) {
    flow.fillVolume(xa, xb, ya, yb, volume);
    updateVolume();
  }
  void addVolume(real x, real y, real radius, real volume) {
    flow.addVolume(x, y, radius, volume);
    updateVolume();
  }

  void updateVolume() { waterVolume = flow.totalVolume() - displacedVolume; }

  // Versamento di un volume V (m^3) con quantita' di moto: il raggio di
  // deposito NON e' un numero a mano ma deriva dal volume (calotta
  // semisferica di pari volume, r = cbrt(3V / 2pi), almeno mezza cella). Il
  // resto lo fa il solutore: la velocita' di espansione e' quella del fronte
  // (sqrt(g h) con h = profondita' risultante), quindi cresce con il volume.
  // (vx, vy) = velocita' orizzontale del getto all'impatto [m/s].
  void addVolumeSpread(real x, real y, real volume, real vx = 0.0,
                       real vy = 0.0) {
    if (!(volume > 0.0) || !std::isfinite(volume))
      return;
    const real r =
        std::max(std::cbrt(3.0 * volume / (2.0 * PI)), 0.5 * flow.dx);
    const real before = flow.totalVolume();
    addVolume(x, y, r, volume);
    const real applied = flow.totalVolume() - before;
    if (applied > 0.0 && (vx != 0.0 || vy != 0.0))
      flow.addMomentum(x, y, r, flow.liquid.rho * applied * vx,
                       flow.liquid.rho * applied * vy);
  }

  real density() const { return flow.liquid.rho; }
  real totalVolume() const { return flow.totalVolume(); }
  std::size_t wetCells() const { return flow.wetCells(); }
  real maxDepth() const { return flow.maxDepth(); }
  real depthAt(real x, real y) const { return flow.depthAt(x, y); }
  bool isInsideBasin(real x, real y) const { return flow.depthAt(x, y) > 1e-4; }

  real surfaceHeight(real x, real y) const {
    auto s = flow.sample(x, y);
    return s.wet ? s.eta : -1e9;
  }

  // La quota della superficie e' SOLO quella del solutore di flusso: le onde
  // (tuffi, oggetti, vento) sono onde vere del campo eta, non decorazioni.
  real surfaceHeightVisual(real x, real y, real) const {
    auto s = flow.sample(x, y);
    return s.wet ? s.eta : -1e9;
  }
  real evaluateHeight(real x, real y, real time) const {
    return surfaceHeightVisual(x, y, time);
  }

  Vec3 velocityAt(real x, real y) const {
    auto s = flow.sample(x, y);
    return s.wet ? Vec3(s.u, s.v, 0) : Vec3(0, 0, 0);
  }

  Vec3 evaluateNormal(real x, real y, real) const {
    auto c = flow.sample(x, y);
    if (!c.wet)
      return Vec3(0, 0, 1);
    const real e = 0.5 * flow.dx;
    const real inv2e = 1.0 / (2.0 * e);
    auto sx1 = flow.sample(x + e, y), sx0 = flow.sample(x - e, y);
    auto sy1 = flow.sample(x, y + e), sy0 = flow.sample(x, y - e);
    real ex1 = sx1.wet ? sx1.eta : c.eta, ex0 = sx0.wet ? sx0.eta : c.eta;
    real ey1 = sy1.wet ? sy1.eta : c.eta, ey0 = sy0.wet ? sy0.eta : c.eta;
    real dhdx = (ex1 - ex0) * inv2e;
    real dhdy = (ey1 - ey0) * inv2e;
    return Vec3(-dhdx, -dhdy, 1.0).normalized();
  }

  // Quota di superficie estesa: acqua dove c'e', altrimenti il fondo (la riva
  // scende in modo continuo sul fondo). Nei solidi (pareti) usa il centro.
  real surfaceOrBed(real x, real y, real fallback) const {
    auto s = flow.sample(x, y);
    if (s.wet)
      return s.eta;
    const real b = flow.bedAt(x, y);
    return b > 0.5 * fluid::ShallowFlow::SOLID_Z ? fallback : b;
  }

  // Normale visiva: solo la pendenza del pelo libero (vicini asciutti = quota
  // del centro, mai la pendenza del fondo/sabbia), passo di differenza = 1
  // cella (la ricostruzione bilineare ha normali discontinue ai bordi cella:
  // allargare lo stencil elimina il reticolo nei riflessi) e dissolvenza verso
  // la verticale quando il film e' sottile (nessuna riga scura sulla riva).
  Vec3 evaluateNormalVisual(real x, real y, real time) const {
    (void)time;
    const auto c = flow.sampleRaw(x, y);
    if (!c.valid)
      return Vec3(0, 0, 1);
    const real e = std::max(flow.dx, 0.05);
    const real inv2e = 1.0 / (2.0 * e);
    auto etaAt = [&](real xx, real yy) {
      const auto r = flow.sampleRaw(xx, yy);
      return (r.valid && r.depth > flow.visibleDepth) ? r.eta : c.eta;
    };
    const real dhdx = (etaAt(x + e, y) - etaAt(x - e, y)) * inv2e;
    const real dhdy = (etaAt(x, y + e) - etaAt(x, y - e)) * inv2e;
    const real t = std::clamp(c.depth / 0.004, 0.0, 1.0);
    const real w = t * t * (3.0 - 2.0 * t);
    return Vec3(-dhdx * w, -dhdy * w, 1.0).normalized();
  }

  real currentLevel() const {
    auto s = flow.sample(basinCenter.x, basinCenter.y);
    return s.wet ? s.depth : 0.0;
  }
  bool isInsideSpillway(real x, real y) const {
    const real half = 3.0;
    return !(std::abs(x - basinCenter.x) <= half &&
             std::abs(y - basinCenter.y) <= half);
  }

  // Perturbazione fisica della superficie (volume conservato): l'onda e'
  // propagata dal solutore (velocita' sqrt(g h), riflessione, attrito).
  void addImpulse(const Vec3 &pos, real /*time*/, real amplitude) {
    if (!std::isfinite(amplitude) || amplitude <= 0.0)
      return;
    auto s = flow.sample(pos.x, pos.y);
    if (!s.wet)
      return;
    const real amp = std::min(amplitude, 0.5 * s.depth);
    flow.addDisturbance(pos.x, pos.y, std::max(0.06, 1.2 * flow.dx), amp);
  }

  // Raggio vs pelo libero. Ray marching sulla superficie CONTINUA (sampleRaw:
  // eta = fondo dove non c'e' acqua) con passo adattivo limitato dalla
  // distanza verticale: un film sottile o un bordo radente non puo' essere
  // "saltato" (prima: passo fisso >= dx/2 -> riva a segmenti e righe scure).
  // Il film e' accettato solo se la profondita' alla radice e' visibile.
  bool intersectWater(const Vec3 &ro, const Vec3 &rd, real time, real &tOut,
                      Vec3 &nOut, real &depthOut, real tMax = 1e30) const {
    (void)time;
    if (!flow.hasWet)
      return false;
    // tMax: distanza della prima superficie opaca gia' trovata; il raggio
    // non cerca acqua oltre (osservatore: si risolve solo cio' che si vede)
    real tN = 0.001, tF = tMax;
    auto slab = [&](real o, real d, real lo, real hi) {
      if (std::abs(d) < 1e-12)
        return o >= lo && o <= hi;
      real t1 = (lo - o) / d, t2 = (hi - o) / d;
      if (t1 > t2)
        std::swap(t1, t2);
      tN = std::max(tN, t1);
      tF = std::min(tF, t2);
      return tN <= tF;
    };
    if (!slab(ro.x, rd.x, flow.bxMin, flow.bxMax) ||
        !slab(ro.y, rd.y, flow.byMin, flow.byMax) ||
        !slab(ro.z, rd.z, flow.bzMin - 0.5, flow.bzMax + 0.5))
      return false;

    fluid::ShallowFlow::Raw raw;
    // g(t) = quota del raggio - quota della superficie (>0: sopra l'acqua)
    auto gOf = [&](real t) {
      const Vec3 p = ro + rd * t;
      raw = flow.sampleRaw(p.x, p.y);
      return raw.valid ? p.z - raw.eta : 1e9;
    };
    real gPrev = gOf(tN);
    if (gPrev <= 0.0 && raw.valid && raw.depth > flow.visibleDepth)
      return false; // l'osservatore parte sott'acqua
    const real dx = flow.dx;
    const real slope =
        std::abs(rd.z) + 0.3; // |dg/dt| massimo (pendenza <= 0.3)
    real tPrev = tN, t = tN;
    for (int it = 0; it < 6000 && t < tF; ++it) {
      real step = dx;
      if (raw.valid) {
        const real gap = std::abs(gPrev);
        step = std::clamp(0.8 * gap / slope, 0.25 * dx, 2.0 * dx);
      }
      tPrev = t;
      t = std::min(t + step, tF);
      const real g = gOf(t);
      if (gPrev > 0.0 && g <= 0.0) {
        real lo = tPrev, hi = t;
        for (int b = 0; b < 16; ++b) {
          const real mid = 0.5 * (lo + hi);
          if (gOf(mid) > 0.0)
            lo = mid;
          else
            hi = mid;
        }
        gOf(hi);
        if (raw.valid && raw.depth > flow.visibleDepth) {
          const Vec3 p = ro + rd * hi;
          tOut = hi;
          nOut = evaluateNormalVisual(p.x, p.y, time);
          depthOut = std::max(1e-4, raw.depth);
          return true;
        }
        // film non visibile: il raggio lo attraversa, si continua
        gPrev = -1.0;
        continue;
      }
      gPrev = g;
      if (t >= tF)
        break;
    }
    return false;
  }

  static bool refractRay(const Vec3 &I, const Vec3 &N, real eta,
                         Vec3 &refracted) {
    real nDotI = N.dot(I);
    real cosThetaI = -nDotI;
    Vec3 norm = N;
    if (cosThetaI < 0) {
      cosThetaI = -cosThetaI;
      norm = N * (-1.0);
      eta = 1.0 / eta;
    }
    real sin2ThetaT = eta * eta * (1.0 - cosThetaI * cosThetaI);
    if (sin2ThetaT > 1.0)
      return false;
    real cosThetaT = std::sqrt(1.0 - sin2ThetaT);
    refracted = (I * eta + norm * (eta * cosThetaI - cosThetaT)).normalized();
    return true;
  }

  static real fresnelDielectric(real cosTheta, real n1 = 1.0, real n2 = 1.333) {
    real r0 = (n1 - n2) / (n1 + n2);
    r0 = r0 * r0;
    return r0 +
           (1.0 - r0) * std::pow(1.0 - std::clamp(cosTheta, 0.0, 1.0), 5.0);
  }

  Vec3 beerLambertTransmission(real pathLength) const {
    return Vec3(std::exp(-absorptionCoeff.x * pathLength),
                std::exp(-absorptionCoeff.y * pathLength),
                std::exp(-absorptionCoeff.z * pathLength));
  }

  static real segmentArea(real r, real h) {
    h = std::clamp(h, 0.0, 2.0 * r);
    if (h <= 0)
      return 0;
    if (h >= 2.0 * r)
      return PI * r * r;
    const real d = r - h;
    return r * r * std::acos(std::clamp(d / r, -1.0, 1.0)) -
           d * std::sqrt(std::max(0.0, 2.0 * r * h - h * h));
  }

  real couple(real cx, real cy, real hx, real hy, bool circular, real dVolume,
              real px, real py) {
    const real margin = 1.5 * flow.dx;
    const real appliedVolume =
        flow.addVolumeRing(cx, cy, hx, hy, circular, margin, dVolume);
    displacedVolume += appliedVolume;
    flow.addMomentum(cx, cy, std::max(hx, hy) + 2.0 * flow.dx, px, py);
    updateVolume();
    return appliedVolume;
  }
};

