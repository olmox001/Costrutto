class ContinuousSandDuneField {
public:
  Vec3 sandCenter = Vec3(3.2, 2.5, 0.0);
  real sandRadius = 2.2;
  real criticalSlope = 0.65;

  static constexpr int GRID_N = 64;
  std::array<std::array<real, GRID_N>, GRID_N> height{};
  real gridSpacing = 0.08;

  ContinuousSandDuneField() {
    for (int j = 0; j < GRID_N; ++j)
      for (int i = 0; i < GRID_N; ++i) {
        real x = (i - GRID_N / 2) * gridSpacing;
        real y = (j - GRID_N / 2) * gridSpacing;
        real r = std::sqrt(x * x + y * y);
        height[j][i] = (r < 1.4) ? std::max(0.0, (1.4 - r) * 0.58) : 0.0;
      }
  }

  // Massimo dell'altezza in cache: il rendering lo chiedeva a OGNI raggio
  // scandendo 64x64 celle. Invalidato da ogni modifica fatta da questa classe.
  mutable real hMaxCache_ = 0.0;
  mutable bool hMaxValid_ = false;
  real hMaxCached() const {
    if (!hMaxValid_) {
      real m = 0.0;
      for (const auto &row : height)
        for (real v : row)
          m = std::max(m, v);
      hMaxCache_ = m;
      hMaxValid_ = true;
    }
    return hMaxCache_;
  }
  void invalidateBounds() { hMaxValid_ = false; }

  void pourSand(real worldX, real worldY, real amount = 0.02) {
    hMaxValid_ = false;
    real localX = worldX - sandCenter.x;
    real localY = worldY - sandCenter.y;
    int i = int(localX / gridSpacing) + GRID_N / 2;
    int j = int(localY / gridSpacing) + GRID_N / 2;
    if (i >= 2 && i < GRID_N - 2 && j >= 2 && j < GRID_N - 2) {
      height[j][i] += amount;
      relaxAvalanche();
    }
  }

  void relaxAvalanche(int iterations = 4) {
    hMaxValid_ = false;
    const real inv_dx = 1.0 / gridSpacing;
    static const int dirs[4][2] = {{1, 0}, {-1, 0}, {0, 1}, {0, -1}};
    for (int iter = 0; iter < iterations; ++iter)
      for (int j = 1; j < GRID_N - 1; ++j)
        for (int i = 1; i < GRID_N - 1; ++i) {
          real hC = height[j][i];
          real maxDiff = 0.0;
          int bestDi = 0, bestDj = 0;
          for (auto &d : dirs) {
            real hN = height[j + d[1]][i + d[0]];
            real diff = hC - hN;
            if (diff > maxDiff) {
              maxDiff = diff;
              bestDi = d[0];
              bestDj = d[1];
            }
          }
          real slope = maxDiff * inv_dx;
          if (slope > criticalSlope) {
            real transfer = (slope - criticalSlope) * gridSpacing * 0.25;
            height[j][i] -= transfer;
            height[j + bestDj][i + bestDi] += transfer;
          }
        }
  }

  real sampleHeight(real worldX, real worldY) const {
    real localX = worldX - sandCenter.x;
    real localY = worldY - sandCenter.y;
    real fi = localX / gridSpacing + GRID_N / 2.0;
    real fj = localY / gridSpacing + GRID_N / 2.0;
    int i0 = int(std::floor(fi));
    int j0 = int(std::floor(fj));
    if (i0 < 0 || i0 >= GRID_N - 1 || j0 < 0 || j0 >= GRID_N - 1)
      return 0.0;
    real u = fi - i0, v = fj - j0;
    real h00 = height[j0][i0];
    real h10 = height[j0][i0 + 1];
    real h01 = height[j0 + 1][i0];
    real h11 = height[j0 + 1][i0 + 1];
    return (h00 * (1 - u) + h10 * u) * (1 - v) + (h01 * (1 - u) + h11 * u) * v;
  }

  Vec3 evaluateNormal(real worldX, real worldY) const {
    const real eps = 0.04;
    const real inv2e = 1.0 / (2.0 * eps);
    real hL = sampleHeight(worldX - eps, worldY);
    real hR = sampleHeight(worldX + eps, worldY);
    real hD = sampleHeight(worldX, worldY - eps);
    real hU = sampleHeight(worldX, worldY + eps);
    real dhdx = (hR - hL) * inv2e;
    real dhdy = (hU - hD) * inv2e;
    return Vec3(-dhdx, -dhdy, 1.0).normalized();
  }

  bool intersectSand(const Vec3 &ro, const Vec3 &rd, real &tOut,
                     Vec3 &nOut) const {
    // Intervallo del raggio dentro la scatola [griglia] x [0, hMax].
    const real half = 0.5 * GRID_N * gridSpacing;
    const real hMax = hMaxCached();
    if (hMax <= 0.005)
      return false;
    real t0 = 1e-5,
         t1 = 1e30; // i raggi sotto un film sottile partono a mm dalla sabbia
    auto slab = [&](real o, real d, real lo, real hi) {
      if (std::abs(d) < 1e-12)
        return o >= lo && o <= hi;
      real a = (lo - o) / d, b = (hi - o) / d;
      if (a > b)
        std::swap(a, b);
      t0 = std::max(t0, a);
      t1 = std::min(t1, b);
      return t0 <= t1;
    };
    if (!slab(ro.x, rd.x, sandCenter.x - half, sandCenter.x + half) ||
        !slab(ro.y, rd.y, sandCenter.y - half, sandCenter.y + half) ||
        !slab(ro.z, rd.z, 0.0, hMax + 1e-3))
      return false;
    // passo <= mezza cella lungo il raggio (campo bilineare: nessuna banda)
    const real stepLen = 0.4 * gridSpacing;
    const int steps = std::clamp(int(std::ceil((t1 - t0) / stepLen)), 2, 512);
    const real dt = (t1 - t0) / steps;
    real tPrev = t0;
    Vec3 pp = ro + rd * tPrev;
    real dPrev = pp.z - sampleHeight(pp.x, pp.y);
    for (int s = 1; s <= steps; ++s) {
      const real tc = t0 + s * dt;
      const Vec3 pc = ro + rd * tc;
      const real dCur = pc.z - sampleHeight(pc.x, pc.y);
      if (dPrev >= 0.0 && dCur <= 0.0) {
        real lo = tPrev, hi = tc;
        for (int b = 0; b < 12; ++b) {
          const real mid = 0.5 * (lo + hi);
          const Vec3 pm = ro + rd * mid;
          if (pm.z - sampleHeight(pm.x, pm.y) > 0.0)
            lo = mid;
          else
            hi = mid;
        }
        const Vec3 ph = ro + rd * hi;
        if (sampleHeight(ph.x, ph.y) <= 0.002)
          return false;
        tOut = hi;
        nOut = evaluateNormal(ph.x, ph.y);
        return true;
      }
      tPrev = tc;
      dPrev = dCur;
    }
    return false;
  }
};

