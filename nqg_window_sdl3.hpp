// ----------------------------------------------------------------------------
// Gestione degli Input (Tastiera + Mouse + Touch / Virtual Joystick)
// ----------------------------------------------------------------------------
class InputManager {
public:
  void resetPerFrame() {
    mouseDeltaX_ = 0.0f;
    mouseDeltaY_ = 0.0f;
    mouseWheelY_ = 0.0f;
    lookDeltaX_ = 0.0f;
    lookDeltaY_ = 0.0f;
    justPressedKeys_.clear();
  }

  void processEvent(const SDL_Event &event) {
    switch (event.type) {
    case SDL_EVENT_KEY_DOWN: {
      SDL_Scancode sc = event.key.scancode;
      if (!isKeyDown(sc)) {
        justPressedKeys_.push_back(sc);
      }
      keys_[sc] = true;
      break;
    }
    case SDL_EVENT_KEY_UP: {
      keys_[event.key.scancode] = false;
      break;
    }
    case SDL_EVENT_MOUSE_MOTION: {
      mouseDeltaX_ += event.motion.xrel;
      mouseDeltaY_ += event.motion.yrel;
      mouseX_ = event.motion.x;
      mouseY_ = event.motion.y;
      break;
    }
    case SDL_EVENT_MOUSE_BUTTON_DOWN: {
      if (event.button.button == SDL_BUTTON_LEFT)
        mouseLeft_ = true;
      if (event.button.button == SDL_BUTTON_RIGHT)
        mouseRight_ = true;
      break;
    }
    case SDL_EVENT_MOUSE_BUTTON_UP: {
      if (event.button.button == SDL_BUTTON_LEFT)
        mouseLeft_ = false;
      if (event.button.button == SDL_BUTTON_RIGHT)
        mouseRight_ = false;
      break;
    }
    case SDL_EVENT_MOUSE_WHEEL: {
      mouseWheelY_ += event.wheel.y;
      break;
    }
    // ---- Touch / Virtual joystick (iOS, Android, trackpad) ----
    case SDL_EVENT_FINGER_DOWN: {
      const SDL_FingerID id = event.tfinger.fingerID;
      const float nx = event.tfinger.x; // 0..1
      const float ny = event.tfinger.y;
      FingerState fs;
      fs.id = id;
      fs.startX = nx;
      fs.startY = ny;
      fs.curX = nx;
      fs.curY = ny;
      // Left half of screen → movement stick, right half → look
      if (nx < 0.45f) {
        fs.role = FingerRole::Move;
        // Only one move stick at a time
        if (moveFingerId_ == 0) {
          moveFingerId_ = id;
          moveOriginX_ = nx;
          moveOriginY_ = ny;
        } else {
          fs.role = FingerRole::None; // ignore extra left fingers
        }
      } else {
        fs.role = FingerRole::Look;
        if (lookFingerId_ == 0) {
          lookFingerId_ = id;
        } else {
          fs.role = FingerRole::None;
        }
      }
      fingers_[id] = fs;
      break;
    }
    case SDL_EVENT_FINGER_MOTION: {
      const SDL_FingerID id = event.tfinger.fingerID;
      auto it = fingers_.find(id);
      if (it == fingers_.end())
        break;
      FingerState &fs = it->second;
      fs.curX = event.tfinger.x;
      fs.curY = event.tfinger.y;
      if (fs.role == FingerRole::Move && id == moveFingerId_) {
        // dead-zone + clamp radius
        const float dx = fs.curX - moveOriginX_;
        const float dy = fs.curY - moveOriginY_;
        const float len = std::sqrt(dx * dx + dy * dy);
        const float maxR = 0.12f; // ~12% of screen width
        const float dead = 0.015f;
        if (len > dead) {
          const float scale = std::min(1.0f, (len - dead) / (maxR - dead));
          moveAxisX_ = (dx / len) * scale;
          moveAxisY_ = (dy / len) * scale; // +Y = down on screen → backward
        } else {
          moveAxisX_ = 0.0f;
          moveAxisY_ = 0.0f;
        }
      } else if (fs.role == FingerRole::Look && id == lookFingerId_) {
        // Relative motion (screen-space delta, inverted Y for look)
        lookDeltaX_ += event.tfinger.dx * 400.0f; // sensitivity scale
        lookDeltaY_ += event.tfinger.dy * 400.0f;
      }
      break;
    }
    case SDL_EVENT_FINGER_UP: {
      const SDL_FingerID id = event.tfinger.fingerID;
      auto it = fingers_.find(id);
      if (it == fingers_.end())
        break;
      if (id == moveFingerId_) {
        moveFingerId_ = 0;
        moveAxisX_ = 0.0f;
        moveAxisY_ = 0.0f;
      }
      if (id == lookFingerId_) {
        lookFingerId_ = 0;
      }
      fingers_.erase(it);
      break;
    }
    default:
      break;
    }
  }

  bool isKeyDown(SDL_Scancode sc) const {
    if (sc >= 0 && static_cast<std::size_t>(sc) < keys_.size()) {
      return keys_[sc];
    }
    return false;
  }

  bool wasKeyPressed(SDL_Scancode sc) const {
    return std::find(justPressedKeys_.begin(), justPressedKeys_.end(), sc) !=
           justPressedKeys_.end();
  }

  float mouseDeltaX() const { return mouseDeltaX_; }
  float mouseDeltaY() const { return mouseDeltaY_; }
  float mouseWheelY() const { return mouseWheelY_; }
  float mouseX() const { return mouseX_; }
  float mouseY() const { return mouseY_; }
  bool isMouseLeftDown() const { return mouseLeft_; }
  bool isMouseRightDown() const { return mouseRight_; }

  // Virtual joystick axes (-1..+1). Y positive = screen-down = backward.
  float moveAxisX() const { return moveAxisX_; }
  float moveAxisY() const { return moveAxisY_; }
  bool hasTouchMove() const { return moveFingerId_ != 0; }
  bool hasTouchLook() const { return lookFingerId_ != 0; }
  float lookDeltaX() const { return lookDeltaX_; }
  float lookDeltaY() const { return lookDeltaY_; }

  // Convenience: is any movement input active (keys or touch)
  bool wantsForward() const {
    return isKeyDown(SDL_SCANCODE_W) || (hasTouchMove() && moveAxisY_ < -0.25f);
  }
  bool wantsBack() const {
    return isKeyDown(SDL_SCANCODE_S) || (hasTouchMove() && moveAxisY_ > 0.25f);
  }
  bool wantsLeft() const {
    return isKeyDown(SDL_SCANCODE_A) || (hasTouchMove() && moveAxisX_ < -0.25f);
  }
  bool wantsRight() const {
    return isKeyDown(SDL_SCANCODE_D) || (hasTouchMove() && moveAxisX_ > 0.25f);
  }

  // Mappatura automatica sui controlli del motore (thrust radiale, yaw, pitch,
  // orbita)
  engine::Input toEngineInput(real sensitivity = 1.0) const {
    engine::Input in;

    // Spinta radiale: W (in avanti / verso il buco nero) vs S (indietro / fuga)
    if (isKeyDown(SDL_SCANCODE_W) || (hasTouchMove() && moveAxisY_ < -0.2f))
      in.thrustR -= 1.0 * sensitivity;
    if (isKeyDown(SDL_SCANCODE_S) || (hasTouchMove() && moveAxisY_ > 0.2f))
      in.thrustR += 1.0 * sensitivity;

    // Orbita circolare: A (progrado / rotazione attorno) vs D (retrogrado)
    if (isKeyDown(SDL_SCANCODE_A) || (hasTouchMove() && moveAxisX_ < -0.2f))
      in.orbitRate -= 0.6 * sensitivity;
    if (isKeyDown(SDL_SCANCODE_D) || (hasTouchMove() && moveAxisX_ > 0.2f))
      in.orbitRate += 0.6 * sensitivity;

    // Pitch & Yaw da tastiera (Frecce direzionali)
    if (isKeyDown(SDL_SCANCODE_LEFT))
      in.yawRate -= 1.2 * sensitivity;
    if (isKeyDown(SDL_SCANCODE_RIGHT))
      in.yawRate += 1.2 * sensitivity;
    if (isKeyDown(SDL_SCANCODE_UP))
      in.pitchRate += 1.0 * sensitivity;
    if (isKeyDown(SDL_SCANCODE_DOWN))
      in.pitchRate -= 1.0 * sensitivity;

    // Controllo vista col mouse (tasto sinistro premuto) o touch look
    if (mouseLeft_) {
      in.yawRate += mouseDeltaX_ * 0.005 * sensitivity;
      in.pitchRate -= mouseDeltaY_ * 0.005 * sensitivity;
    }
    if (hasTouchLook()) {
      in.yawRate += lookDeltaX_ * 0.005 * sensitivity;
      in.pitchRate -= lookDeltaY_ * 0.005 * sensitivity;
    }

    return in;
  }

  // ---------------------------------------------------------------------------
  // Produce abstract Commands for the capsule observer / game logic.
  // Completely decoupled from SDL once the Commands object is returned.
  // ---------------------------------------------------------------------------
  nqg::cmd::Commands toCommands(float lookSensitivity = 0.0035f) const {
    nqg::cmd::Commands c;

    // Movement: prefer analog stick when active, else digital keys
    if (hasTouchMove()) {
      c.moveX = moveAxisX_;
      c.moveY = -moveAxisY_; // screen-down → back → negative forward
    } else {
      if (isKeyDown(SDL_SCANCODE_W))
        c.moveY += 1.0f;
      if (isKeyDown(SDL_SCANCODE_S))
        c.moveY -= 1.0f;
      if (isKeyDown(SDL_SCANCODE_A))
        c.moveX -= 1.0f;
      if (isKeyDown(SDL_SCANCODE_D))
        c.moveX += 1.0f;
      // normalize diagonal
      const float len2 = c.moveX * c.moveX + c.moveY * c.moveY;
      if (len2 > 1.0f) {
        const float inv = 1.0f / std::sqrt(len2);
        c.moveX *= inv;
        c.moveY *= inv;
      }
    }

    // Look: mouse (while LMB) + touch look + arrows
    if (mouseLeft_) {
      c.lookYaw += mouseDeltaX_ * lookSensitivity;
      c.lookPitch += mouseDeltaY_ * lookSensitivity;
    }
    if (hasTouchLook()) {
      c.lookYaw += lookDeltaX_ * lookSensitivity;
      c.lookPitch += lookDeltaY_ * lookSensitivity;
    }
    // continuous arrow look (rate * ~1 frame; caller multiplies by dt if needed)
    // Here we leave rate-based for arrows as instantaneous delta scaled outside
    // or treat as held → observer can integrate with dt. For simplicity we
    // inject a small per-frame delta; game may also read keys directly.
    if (isKeyDown(SDL_SCANCODE_LEFT))
      c.lookYaw -= 1.6f * 0.016f; // approx one frame at 60 Hz
    if (isKeyDown(SDL_SCANCODE_RIGHT))
      c.lookYaw += 1.6f * 0.016f;
    if (isKeyDown(SDL_SCANCODE_UP))
      c.lookPitch -= 1.2f * 0.016f;
    if (isKeyDown(SDL_SCANCODE_DOWN))
      c.lookPitch += 1.2f * 0.016f;

    c.jumpHeld = isKeyDown(SDL_SCANCODE_SPACE);
    c.jumpPressed = wasKeyPressed(SDL_SCANCODE_SPACE);
    // jumpReleased is set by observer edge logic if needed; here we only
    // expose held/pressed. Observer still tracks release via previous state.
    c.crouch = isKeyDown(SDL_SCANCODE_C);
    c.boost = isKeyDown(SDL_SCANCODE_LSHIFT) || isKeyDown(SDL_SCANCODE_RSHIFT);

    c.action1 = wasKeyPressed(SDL_SCANCODE_1) || isKeyDown(SDL_SCANCODE_1);
    c.action2 = wasKeyPressed(SDL_SCANCODE_2) || isKeyDown(SDL_SCANCODE_2);
    c.action3 = wasKeyPressed(SDL_SCANCODE_3);
    c.toggleWind = wasKeyPressed(SDL_SCANCODE_T);
    c.toggleGravity = wasKeyPressed(SDL_SCANCODE_G);
    c.toggleLight = wasKeyPressed(SDL_SCANCODE_L);
    c.clearDynamics = wasKeyPressed(SDL_SCANCODE_X);
    c.quit = wasKeyPressed(SDL_SCANCODE_ESCAPE);
    c.toggleHud = wasKeyPressed(SDL_SCANCODE_H);
    c.toggleMute = wasKeyPressed(SDL_SCANCODE_M);

    return c;
  }

private:
  enum class FingerRole { None, Move, Look };
  struct FingerState {
    SDL_FingerID id = 0;
    FingerRole role = FingerRole::None;
    float startX = 0, startY = 0;
    float curX = 0, curY = 0;
  };

  std::vector<bool> keys_ = std::vector<bool>(SDL_SCANCODE_COUNT, false);
  std::vector<SDL_Scancode> justPressedKeys_;
  float mouseX_ = 0.0f;
  float mouseY_ = 0.0f;
  float mouseDeltaX_ = 0.0f;
  float mouseDeltaY_ = 0.0f;
  float mouseWheelY_ = 0.0f;
  bool mouseLeft_ = false;
  bool mouseRight_ = false;

  // Touch state
  std::unordered_map<SDL_FingerID, FingerState> fingers_;
  SDL_FingerID moveFingerId_ = 0;
  SDL_FingerID lookFingerId_ = 0;
  float moveOriginX_ = 0.0f;
  float moveOriginY_ = 0.0f;
  float moveAxisX_ = 0.0f;
  float moveAxisY_ = 0.0f;
  float lookDeltaX_ = 0.0f;
  float lookDeltaY_ = 0.0f;
};

// ----------------------------------------------------------------------------
// Sintetizzatore Audio Relativistico (SDL3 AudioStream)
// ----------------------------------------------------------------------------
class RelativisticAudioSynthesizer {
public:
  RelativisticAudioSynthesizer(int sampleRate = 44100)
      : sampleRate_(sampleRate) {}

  ~RelativisticAudioSynthesizer() { shutdown(); }

  bool init() {
    SDL_AudioSpec spec;
    spec.format = SDL_AUDIO_F32;
    spec.channels = 1;
    spec.freq = sampleRate_;

    stream_ = SDL_OpenAudioDeviceStream(SDL_AUDIO_DEVICE_DEFAULT_PLAYBACK,
                                        &spec, nullptr, nullptr);
    if (!stream_) {
      std::fprintf(
          stderr, "[Audio] Warning: Impossible to open SDL3 audio device: %s\n",
          SDL_GetError());
      return false;
    }
    SDL_ResumeAudioStreamDevice(stream_);
    initialized_ = true;
    return true;
  }

  void shutdown() {
    if (stream_) {
      SDL_DestroyAudioStream(stream_);
      stream_ = nullptr;
    }
    initialized_ = false;
  }

  bool isMuted() const { return muted_; }
  void toggleMute() { muted_ = !muted_; }
  void setMuted(bool m) { muted_ = m; }

  struct Transient {
    float freq = 440.0f;
    float amp = 0.0f;
    float decay = 15.0f;
    float phase = 0.0f;
  };

  void triggerTransient(float freq, float intensity, float decay = 25.0f) {
    if (muted_ || !initialized_)
      return;
    Transient t;
    t.freq = std::clamp(freq, 60.0f, 6000.0f);
    t.amp = std::clamp(intensity, 0.0f, 0.6f);
    t.decay = decay;
    t.phase = 0.0f;
    transients_.push_back(t);
  }

  // Genera audio solo se ci sono eventi fisici o flusso d'aria effettivo (zero
  // ronzio di fondo)
  void update(real dt, real lapseAlpha, real beaconNuCoord, real thrustMag,
              real tidalStress) {
    (void)lapseAlpha;
    (void)beaconNuCoord;
    (void)tidalStress;
    if (!initialized_ || !stream_ || muted_)
      return;

    int numSamples = static_cast<int>(dt * sampleRate_);
    numSamples = std::clamp(numSamples, 64, 4096);

    std::vector<float> buffer(numSamples, 0.0f);
    float dtSec = 1.0f / sampleRate_;

    // Se non ci sono transienti attivi e la velocita' e' minima, silenzio
    // assoluto pulito
    if (transients_.empty() && thrustMag < 0.05) {
      // Invia silenzio pulito per mantenere lo stream sincronizzato senza
      // glitch
      SDL_PutAudioStreamData(stream_, buffer.data(),
                             buffer.size() * sizeof(float));
      return;
    }

    for (int i = 0; i < numSamples; ++i) {
      float out = 0.0f;

      // 1. Rumore di flusso d'aria dolce (whoosh aerodinamico sopra soglia,
      // zero ronzio)
      if (thrustMag > 0.08) {
        float white =
            (static_cast<float>(std::rand()) / static_cast<float>(RAND_MAX)) *
                2.0f -
            1.0f;
        // Filtro passa-basso dolce (rumore d'aria naturale, non ronzio
        // elettrico)
        thrusterRumbleFilter_ = 0.95f * thrusterRumbleFilter_ + 0.05f * white;
        float airVolume = static_cast<float>(
            std::clamp((thrustMag - 0.08) * 0.12, 0.0, 0.25));
        out += thrusterRumbleFilter_ * airVolume;
      }

      // 2. Transienti acustici fisici (gocce d'acqua, urti granelli di sabbia,
      // impatti solidi)
      for (auto &tr : transients_) {
        tr.phase += 2.0f * static_cast<float>(nqg::PI) * tr.freq * dtSec;
        if (tr.phase > 2.0f * nqg::PI)
          tr.phase -= 2.0f * static_cast<float>(nqg::PI);
        out += tr.amp * std::sin(tr.phase);
        tr.amp *= (1.0f - tr.decay * dtSec); // Decadimento esponenziale
      }

      buffer[i] = std::clamp(out, -0.8f, 0.8f);
    }

    // Rimuovi transienti esauriti
    transients_.erase(
        std::remove_if(transients_.begin(), transients_.end(),
                       [](const Transient &t) { return t.amp < 0.001f; }),
        transients_.end());

    SDL_PutAudioStreamData(stream_, buffer.data(),
                           buffer.size() * sizeof(float));
  }

private:
  int sampleRate_ = 44100;
  SDL_AudioStream *stream_ = nullptr;
  bool initialized_ = false;
  bool muted_ = false;
  float thrusterRumbleFilter_ = 0.0f;
  std::vector<Transient> transients_;
};

// ----------------------------------------------------------------------------
// Pixel Streamer e Texture Renderer
// ----------------------------------------------------------------------------
class PixelStreamer {
public:
  ~PixelStreamer() { destroyTexture(); }

  void destroyTexture() {
    if (texture_) {
      SDL_DestroyTexture(texture_);
      texture_ = nullptr;
    }
    texW_ = 0;
    texH_ = 0;
  }

  bool updateTexture(SDL_Renderer *renderer, const engine::Image &img) {
    if (!renderer || img.w <= 0 || img.h <= 0)
      return false;

    // Crea o rialloca la texture se le dimensioni sono cambiate
    if (!texture_ || texW_ != img.w || texH_ != img.h) {
      destroyTexture();
      texture_ = SDL_CreateTexture(renderer, SDL_PIXELFORMAT_RGBA32,
                                   SDL_TEXTUREACCESS_STREAMING, img.w, img.h);
      if (!texture_) {
        std::fprintf(stderr, "[PixelStreamer] SDL_CreateTexture failed: %s\n",
                     SDL_GetError());
        return false;
      }
      SDL_SetTextureScaleMode(texture_, SDL_SCALEMODE_LINEAR);
      texW_ = img.w;
      texH_ = img.h;
      rgbaBuffer_.resize(std::size_t(texW_) * texH_);
    }

    // Conversione da float RGB [0, 1] a RGBA32 (0xAABBGGRR / 32-bit packed)
    const std::size_t numPixels = std::size_t(img.w) * img.h;
    for (std::size_t i = 0; i < numPixels; ++i) {
      const float r = std::clamp(img.px[i * 3 + 0], 0.0f, 1.0f);
      const float g = std::clamp(img.px[i * 3 + 1], 0.0f, 1.0f);
      const float b = std::clamp(img.px[i * 3 + 2], 0.0f, 1.0f);

      const uint32_t ir = static_cast<uint32_t>(r * 255.0f);
      const uint32_t ig = static_cast<uint32_t>(g * 255.0f);
      const uint32_t ib = static_cast<uint32_t>(b * 255.0f);

      rgbaBuffer_[i] = (255u << 24) | (ib << 16) | (ig << 8) | ir;
    }

    // Aggiorna lo streaming texture
    return SDL_UpdateTexture(texture_, nullptr, rgbaBuffer_.data(),
                             static_cast<int>(texW_ * sizeof(uint32_t)));
  }

  void render(SDL_Renderer *renderer, int winW, int winH) {
    if (!renderer || !texture_)
      return;

    // Calcola il rettangolo di destinazione mantenendo il rapporto d'aspetto
    // (letterbox/pillarbox)
    float targetAspect = static_cast<float>(texW_) / static_cast<float>(texH_);
    float winAspect = static_cast<float>(winW) / static_cast<float>(winH);

    SDL_FRect dst;
    if (winAspect > targetAspect) {
      dst.h = static_cast<float>(winH);
      dst.w = dst.h * targetAspect;
      dst.x = (winW - dst.w) * 0.5f;
      dst.y = 0.0f;
    } else {
      dst.w = static_cast<float>(winW);
      dst.h = dst.w / targetAspect;
      dst.x = 0.0f;
      dst.y = (winH - dst.h) * 0.5f;
    }

    SDL_RenderTexture(renderer, texture_, nullptr, &dst);
  }

  int textureWidth() const { return texW_; }
  int textureHeight() const { return texH_; }
  const std::vector<uint32_t> &rgbaBuffer() const { return rgbaBuffer_; }

private:
  SDL_Texture *texture_ = nullptr;
  int texW_ = 0;
  int texH_ = 0;
  std::vector<uint32_t> rgbaBuffer_;
};

