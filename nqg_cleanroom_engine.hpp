  void resolvePlayerCollision(Vec3 &camPos, Vec3 &camVel,
                              const CapsuleCollider &cap) {
    const Vec3 vIn =
        camVel; // velocita' prima dei vincoli (per spingere le sfere)
    if (!apartment::isFiniteVec(camPos) || !apartment::isFiniteVec(camVel)) {
      camPos = Vec3(0, 0, cap.eyeHeight);
      camVel = Vec3(0, 0, 0);
      return;
    }
    constexpr real FLAT_RADIUS = 300.0;
    if (camPos.norm2() < FLAT_RADIUS * FLAT_RADIUS) {
      // stanza: shell SDF (pareti, pavimento, soffitto, tetto)
      apartment::resolveCapsuleRoom(camPos, camVel, cap, room);
      // solidi liberi (i primi room.walls.size() sono le pareti, gia' nella
      // shell): campo SDF orientato di ciascun solido
      for (std::size_t i = room.walls.size(); i < solids.size(); ++i) {
        const auto &s = solids[i];
        if (s.isRoomSlab)
          continue;
        if ((camPos - s.pos).norm() > s.boundRadius() + cap.height + 1.0)
          continue;
        sdf::resolveCapsule(
            camPos, camVel, cap.radius, cap.eyeHeight, cap.height,
            [&](const Vec3 &p, Vec3 &n) { return s.distanceGradWorld(p, n); },
            0.005);
      }
      const real h = sand.sampleHeight(camPos.x, camPos.y);
      if (h > 0.001) {
        const real footZ = cap.footZ(camPos.z);
        if (footZ < h) {
          camPos.z += (h - footZ);
          if (camVel.z < 0)
            camVel.z = 0;
        }
      }
    }
    // Il giocatore (capsula cinematica) spinge le sfere: fuori dalla capsula
    // e velocita' normale almeno pari a quella del giocatore.
    for (auto &sp : spheres) {
      const real foot = cap.footZ(camPos.z);
      const real z0 = foot + cap.radius, z1 = foot + cap.height - cap.radius;
      const Vec3 axisP(camPos.x, camPos.y, std::clamp(sp.pos.z, z0, z1));
      const Vec3 d = sp.pos - axisP;
      const real dist = d.norm();
      const real minD = sp.radius + cap.radius;
      if (dist >= minD)
        continue;
      const Vec3 n = dist > 1e-9 ? d * (1.0 / dist) : Vec3(1, 0, 0);
      sp.pos = sp.pos + n * (minD - dist);
      const real rel = (vIn - sp.vel).dot(n);
      if (rel > 0.0)
        sp.vel = sp.vel + n * (rel * 1.2);
    }
    const Vec3 C(0, 0, -earth::planet::R_E);
    const Vec3 r = camPos - C;
    const real rho = r.norm();
    const real minR = earth::planet::R_E + cap.eyeHeight + 0.001;
    if (rho < minR) {
      const Vec3 u = rho > 1e-9 ? r * (1.0 / rho) : Vec3(0, 0, 1);
      camPos = C + u * minR;
      const real vn = camVel.dot(u);
      if (vn < 0)
        camVel = camVel - u * vn;
    }
  }

  void couplePlayer(const Vec3 &camPos, const Vec3 &camVel,
                    const CapsuleCollider &cap, real dt) {
    if (!(dt > 0) || !apartment::isFiniteVec(camPos) ||
        !apartment::isFiniteVec(camVel))
      return;
    playerSubmerged =
        water.couplePlayer(camPos, cap.radius, cap.footZ(camPos.z), cap.height,
                           camVel, dt, playerSubmerged);
  }

  static bool intersectSphere(const Vec3 &ro, const Vec3 &rd,
                              const Vec3 &center, real radius, real &tOut,
                              Vec3 &nOut) {
    Vec3 oc = ro - center;
    real b = oc.dot(rd);
    real c = oc.dot(oc) - radius * radius;
    real disc = b * b - c;
    if (disc < 0 || !std::isfinite(disc))
      return false;
    real sq = std::sqrt(disc);
    real t = -b - sq;
    if (t < 0.001)
      t = -b + sq;
    if (t < 0.001)
      return false;
    tOut = t;
    nOut = apartment::safeNormalize((ro + rd * t) - center);
    return true;
  }

  static bool intersectFloor(const Vec3 &ro, const Vec3 &rd, real &tOut,
                             Vec3 &nOut) {
    if (std::abs(rd.z) < 1e-7)
      return false;
    real t = -ro.z / rd.z;
    if (t < 0.001 || !std::isfinite(t))
      return false;
    tOut = t;
    nOut = Vec3(0, 0, 1);
    return true;
  }

  bool intersectEarth(const Vec3 &ro, const Vec3 &rd, real &tOut, Vec3 &nOut,
                      real &latOut, real &lonOut) const {
    const real R = earth::planet::R_E;
    const Vec3 C(0, 0, -R);
    Vec3 oc = ro - C;
    const real b = oc.dot(rd);
    // c = (|oc|-R)(|oc|+R): niente cancellazione catastrofica vicino al suolo
    const real ocN = oc.norm();
    const real c = (ocN - R) * (ocN + R);
    const real disc = b * b - c;
    if (disc < 0 || !std::isfinite(disc))
      return false;
    const real sq = std::sqrt(disc);
    // radici stabili: q = -(b + sgn(b) sq),  t0 = q,  t1 = c/q
    const real q = -(b + (b >= 0.0 ? sq : -sq));
    real ta = q, tb = q != 0.0 ? c / q : q;
    if (ta > tb)
      std::swap(ta, tb);
    // Un film d'acqua puo' essere spesso meno di 1 mm: la soglia dev'essere
    // minuscola, altrimenti si scarta la radice vicina e si prende il lato
    // opposto del pianeta (pixel neri sui bordi del film).
    constexpr real TMIN = 1e-7;
    real t = ta;
    if (t < TMIN)
      t = tb;
    if (t < TMIN)
      return false;
    Vec3 hitLocal = ro + rd * t;
    Vec3 hitECEF = localToECEF(hitLocal);
    real alt;
    earth::EarthGlobe::ecefToLatLon(hitECEF, latOut, lonOut, alt);
    tOut = t;
    nOut = apartment::safeNormalize(hitLocal - C);
    return true;
  }

  static void overlayGrid(Rgb &col, real lat, real lon, real lineWidthDeg) {
    real step = 1.0 * PI / 180.0;
    real fLat = std::abs(std::fmod(lat, step)) / step;
    real fLon = std::abs(std::fmod(lon, step)) / step;
    real dLat = std::min(fLat, 1.0 - fLat);
    real dLon = std::min(fLon, 1.0 - fLon);
    real d = std::min(dLat, dLon);
    real lw = lineWidthDeg / 180.0;
    if (d < lw) {
      real g = 1.0 - d / lw;
      col.r = col.r * (1.0f - 0.55f * float(g)) + 0.08f * float(g);
      col.g = col.g * (1.0f - 0.55f * float(g)) + 0.88f * float(g);
      col.b = col.b * (1.0f - 0.55f * float(g)) + 1.00f * float(g);
    }
  }

  real terrainDetail(real lat, real lon) const {
    real h = 0.0;
    h += 25.0 * std::sin(lat * 421.0 + 5.3) * std::cos(lon * 389.0 + 2.1);
    h += 10.0 * std::sin(lat * 1130.0 + 7.7) * std::cos(lon * 1043.0 + 4.4);
    h += 4.0 * std::sin(lat * 2917.0 + 1.9) * std::cos(lon * 2811.0 + 6.2);
    h += 1.5 * std::sin(lat * 7901.0 + 3.2) * std::cos(lon * 7321.0 + 0.8);
    h += 0.5 * std::sin(lat * 21401.0 + 9.4) * std::cos(lon * 19891.0 + 3.7);
    return h;
  }

  Rgb terrainAlbedoAt(const Vec3 &localPoint) const {
    const Vec3 ecef = localToECEF(localPoint);
    real lat, lon, alt;
    earth::EarthGlobe::ecefToLatLon(ecef, lat, lon, alt);
    auto surf = globe.terrain.sample(lat, lon, 0.0);
    const real detail = terrainDetail(lat, lon);
    const real shade = std::clamp(1.0 + 0.008 * detail, 0.6, 1.4);
    return {std::clamp(surf.albedo.r * float(shade), 0.0f, 1.0f),
            std::clamp(surf.albedo.g * float(shade), 0.0f, 1.0f),
            std::clamp(surf.albedo.b * float(shade), 0.0f, 1.0f)};
  }

  // ---- SDF di scena: unione dei campi di tutti i solidi e delle sfere ----
  bool enableAO = true;
  real aoStrength = 0.9;

  real sceneDistance(const Vec3 &p, real cutoff = 1e9) const {
    real d = 1e9;
    for (const auto &s : solids) {
      if ((p - s.pos).norm() - s.boundRadius() > std::min(d, cutoff))
        continue;
      d = std::min(d, s.distanceWorld(p));
    }
    for (const auto &sp : spheres)
      d = std::min(d, (p - sp.pos).norm() - sp.radius);
    return d;
  }

  // Occlusione ambientale: campiona d(p + n*h) lungo la normale.
  real ambientOcclusion(const Vec3 &pos, const Vec3 &n) const {
    real occ = 0.0, w = 1.0;
    for (int i = 0; i < 4; ++i) {
      const real h = 0.04 + 0.11 * i;
      const real d = sceneDistance(pos + n * h, h + 0.5);
      occ += std::max(0.0, h - d) * w;
      w *= 0.7;
    }
    return std::clamp(1.0 - aoStrength * 2.2 * occ, 0.15, 1.0);
  }

  // Shadow ray con bounding-sphere cull.
  bool isInShadow(const Vec3 &pos, const Vec3 &lightDir, real maxDist) const {
    Vec3 ro = pos + lightDir * 0.005;
    for (const auto &s : solids) {
      if (s.raySphereCull(ro, lightDir))
        continue;
      real t;
      Vec3 n;
      if (s.raycast(ro, lightDir, t, n)) {
        if (t < maxDist)
          return true;
      }
    }
    for (const auto &sp : spheres) {
      real t;
      Vec3 n;
      if (intersectSphere(ro, lightDir, sp.pos, sp.radius, t, n) && t < maxDist)
        return true;
    }
    return false;
  }

  static Rgb floorTexture(const Vec3 &hit) {
    real u = hit.x, v = hit.y;
    real fu = std::abs(u - std::round(u));
    real fv = std::abs(v - std::round(v));
    real edge = std::min(fu, fv);
    real su = std::abs(u * 5.0 - std::round(u * 5.0));
    real sv = std::abs(v * 5.0 - std::round(v * 5.0));
    real subEdge = std::min(su, sv);
    Rgb col = {0.82f, 0.84f, 0.87f};
    int iu = int(std::floor(u)), iv = int(std::floor(v));
    if ((iu + iv) % 2 != 0) {
      col.r *= 0.96f;
      col.g *= 0.96f;
      col.b *= 0.96f;
    }
    if (edge < 0.02)
      return {0.45f, 0.48f, 0.52f};
    if (subEdge < 0.015)
      return {0.75f, 0.78f, 0.82f};
    return col;
  }

  Rgb skyColor(const Vec3 &dir) const {
    real rhoRatio = std::clamp(currentDensity / earth::planet::rho0, 0.0, 1.5);
    Vec3 sunDir = apartment::safeNormalize(homeEast * 0.70 + homeUp * 0.55 +
                                           homeNorth * 0.45);
    real cosSun = std::max(0.0, dir.dot(sunDir));
    real baseR = (0.30 + 0.35 * cosSun) * rhoRatio;
    real baseG = (0.48 + 0.30 * cosSun) * rhoRatio;
    real baseB = (0.85 + 0.10 * cosSun) * rhoRatio;
    real sunDisc = std::pow(cosSun, 800.0) * 8.0;
    real skyFade = std::clamp(1.0 - currentAltitude / 60000.0, 0.0, 1.0);
    Rgb col;
    col.r = float(std::clamp(baseR * skyFade + sunDisc, 0.0, 1.5));
    col.g = float(std::clamp(baseG * skyFade + sunDisc, 0.0, 1.5));
    col.b = float(std::clamp(baseB * skyFade + sunDisc * 0.85, 0.0, 1.5));
    if (currentAltitude > 10000.0) {
      real starVis =
          std::clamp((currentAltitude - 10000.0) / 40000.0, 0.0, 1.0);
      std::uint32_t hx = std::uint32_t(int(dir.x * 12000.0) + 100000);
      std::uint32_t hy = std::uint32_t(int(dir.y * 12000.0) + 100000);
      std::uint32_t hz = std::uint32_t(int(dir.z * 12000.0) + 100000);
      real h = engine::h01(hx, hy, hz);
      if (h > 1.0 - 0.003 * starVis) {
        real bright = 0.4 + 0.6 * engine::h01(hx ^ 17u, hy ^ 31u, hz ^ 47u);
        col.r += float(bright * starVis);
        col.g += float(bright * starVis * 0.95);
        col.b += float(bright * starVis * 1.05);
      }
    }
    return col;
  }

  // Shading opaco condiviso: usato sia per le superfici viste direttamente
  // sia per il fondo visto attraverso l'acqua (stesso AO, luci, ombre, nebbia).
  Rgb shadeOpaque(const Vec3 &hitPos, const Vec3 &normal, const Rgb &hitAlbedo,
                  real metallic, real roughness, const Vec3 &viewDir,
                  real tDist, std::size_t nLights) const {
    Rgb lit = {0.0f, 0.0f, 0.0f};
    real hemi = 0.5 * (normal.z + 1.0);
    Rgb ambient = {
        float(cachedAmbientGround.r * (1.0 - hemi) + cachedAmbientSky.r * hemi),
        float(cachedAmbientGround.g * (1.0 - hemi) + cachedAmbientSky.g * hemi),
        float(cachedAmbientGround.b * (1.0 - hemi) +
              cachedAmbientSky.b * hemi)};
    const real ao = (enableAO && hitPos.norm2() < 2500.0)
                        ? ambientOcclusion(hitPos, normal)
                        : 1.0;
    lit.r += float(hitAlbedo.r * ambient.r * ao);
    lit.g += float(hitAlbedo.g * ambient.g * ao);
    lit.b += float(hitAlbedo.b * ambient.b * ao);
    for (std::size_t li = 0; li < nLights; ++li) {
      const auto &L = lighting.lights[li];
      if (!L.active)
        continue;
      Vec3 toLight;
      real dist = 1e6, atten = 1.0;
      if (L.type == LightSource::Type::Directional) {
        toLight = L.direction * (-1.0);
        dist = 1000.0;
        atten = 1.0;
      } else {
        toLight = L.position - hitPos;
        dist = toLight.norm();
        if (dist > 1e-4)
          toLight = toLight * (1.0 / dist);
        atten = 1.0 / (1.0 + 0.12 * dist + 0.03 * dist * dist);
      }
      // nDotL PRIMA della shadow ray
      const real nDotL = std::max(0.0, normal.dot(toLight));
      if (nDotL <= 0.0)
        continue;
      if (isInShadow(hitPos, toLight, dist))
        continue;
      const Rgb &lCol = cachedLightColors[li];
      const Vec3 halfVec = apartment::safeNormalize(toLight + viewDir);
      const real nDotH = std::max(0.0, normal.dot(halfVec));
      const real specPower = std::max(2.0, (1.0 - roughness) * 128.0);
      const real spec = std::pow(nDotH, specPower);
      const real vDotH = std::max(0.0, viewDir.dot(halfVec));
      const real f0 = 0.04 * (1.0 - metallic) + metallic;
      const real fresnel = f0 + (1.0 - f0) * std::pow(1.0 - vDotH, 5.0);
      const real diffFactor = (1.0 - metallic) * nDotL * atten;
      const real specFactor = spec * fresnel * atten * 1.5;
      lit.r += float(hitAlbedo.r * lCol.r * diffFactor + lCol.r * specFactor);
      lit.g += float(hitAlbedo.g * lCol.g * diffFactor + lCol.g * specFactor);
      lit.b += float(hitAlbedo.b * lCol.b * diffFactor + lCol.b * specFactor);
    }
    const real effScat = effectiveScattering();
    const real ext = effScat * tDist;
    const real transmission = std::exp(-ext);
    const real inScatter = 1.0 - transmission;
    const Rgb haze = skyColor(viewDir * -1.0);
    lit.r = float(lit.r * transmission + haze.r * inScatter * 0.9);
    lit.g = float(lit.g * transmission + haze.g * inScatter * 0.9);
    lit.b = float(lit.b * transmission + haze.b * inScatter * 0.9);
    return lit;
  }

  Rgb traceRay(const Vec3 &ro, const Vec3 &rd) const {
    const std::size_t nLights = cachedLightColors.size();

    bool cameraUnderwater = false;
    {
      if (water.isInsideBasin(ro.x, ro.y)) {
        const real eta = water.surfaceHeightVisual(ro.x, ro.y, simTime);
        if (eta > -1e8 && ro.z < eta)
          cameraUnderwater = true;
      }
    }

    real tHit = 1e9;
    Vec3 normal;
    Rgb hitAlbedo;
    real metallic = 0.0, roughness = 0.5;
    bool hitSomething = false, hitWater = false, hitQuantum = false;

    for (const auto &s : solids) {
      if (s.raySphereCull(ro, rd))
        continue;
      real tBox;
      Vec3 nBox;
      if (s.raycast(ro, rd, tBox, nBox)) {
        if (tBox < tHit && std::isfinite(tBox)) {
          tHit = tBox;
          normal = nBox;
          hitAlbedo = s.albedo;
          metallic = s.metallic;
          roughness = s.roughness;
          hitSomething = true;
          hitWater = false;
          hitQuantum = false;
        }
      }
    }
    for (const auto &sp : spheres) {
      real tSph;
      Vec3 nSph;
      if (intersectSphere(ro, rd, sp.pos, sp.radius, tSph, nSph) &&
          tSph < tHit && std::isfinite(tSph)) {
        tHit = tSph;
        normal = nSph;
        hitAlbedo = sp.albedo;
        metallic = sp.metallic;
        roughness = sp.roughness;
        hitSomething = true;
        hitWater = false;
        hitQuantum = false;
      }
    }
    real tW = -1.0, dW = 0.0, waterDepth = -1.0;
    Vec3 nW;
    if (water.intersectWater(ro, rd, simTime, tW, nW, dW)) {
      if (tW < tHit && std::isfinite(tW)) {
        tHit = tW;
        normal = nW;
        hitSomething = true;
        hitWater = true;
        hitQuantum = false;
        waterDepth = dW;
      }
    }
    real tS;
    Vec3 nS;
    if (sand.intersectSand(ro, rd, tS, nS)) {
      if (tS < tHit && std::isfinite(tS)) {
        tHit = tS;
        normal = nS;
        hitAlbedo = {0.86f, 0.74f, 0.44f};
        metallic = 0.0;
        roughness = 0.88;
        hitSomething = true;
        hitWater = false;
        hitQuantum = false;
      }
    }
    {
      Vec3 qDiff = ro - quantumField.center;
      real qB = qDiff.dot(rd);
      real qR = quantumField.sigma * 4.0;
      real qC = qDiff.dot(qDiff) - qR * qR;
      real qDisc = qB * qB - qC;
      if (qDisc > 0 && (-qB - std::sqrt(qDisc)) < tHit) {
        real tQEntry = std::max(0.01, -qB - std::sqrt(qDisc));
        real tQExit = -qB + std::sqrt(qDisc);
        if (tQEntry < tHit && tQExit > 0.01) {
          real accum = 0;
          const int QSTEPS = 16;
          real qdt = (std::min(tQExit, tHit) - tQEntry) / QSTEPS;
          for (int qi = 0; qi < QSTEPS; ++qi) {
            Vec3 qp = ro + rd * (tQEntry + (qi + 0.5) * qdt);
            accum += quantumField.evaluateDensity(qp) * qdt;
          }
          if (accum > 0.001) {
            real alpha = std::min(1.0, accum * 5.0);
            hitQuantum = (alpha > 0.02 && tQEntry < tHit);
          }
        }
      }
    }
    {
      real tE;
      Vec3 nE;
      real latHit, lonHit;
      if (intersectEarth(ro, rd, tE, nE, latHit, lonHit)) {
        if (tE < tHit && std::isfinite(tE)) {
          auto surf = globe.terrain.sample(latHit, lonHit, 0.0);
          real detail = terrainDetail(latHit, lonHit);
          real shade = std::clamp(1.0 + 0.008 * detail, 0.6, 1.4);
          hitAlbedo.r = std::clamp(surf.albedo.r * float(shade), 0.0f, 1.0f);
          hitAlbedo.g = std::clamp(surf.albedo.g * float(shade), 0.0f, 1.0f);
          hitAlbedo.b = std::clamp(surf.albedo.b * float(shade), 0.0f, 1.0f);
          metallic = 0.0;
          roughness = std::min(1.0, surf.roughness * 1.8);
          hitWater = (surf.type == earth::SurfaceType::Water);
          waterDepth = -1.0; // il mare terrestre non e' il film del solutore
          real lw = 0.08 + std::clamp(200.0 / std::max(1.0, tE), 0.0, 0.5);
          overlayGrid(hitAlbedo, latHit, lonHit, lw);
          tHit = tE;
          normal = nE;
          hitSomething = true;
          hitQuantum = false;
        }
      }
    }
    if (!hitSomething && !hitQuantum) {
      Rgb sky = skyColor(rd);
      if (cameraUnderwater) {
        sky.r *= 0.30f;
        sky.g *= 0.55f;
        sky.b *= 0.75f;
      }
      return sky;
    }
    if (hitQuantum && !hitSomething) {
      Vec3 qDiff = ro - quantumField.center;
      real qB = qDiff.dot(rd);
      real qR = quantumField.sigma * 4.0;
      real qC = qDiff.dot(qDiff) - qR * qR;
      real qDisc = qB * qB - qC;
      real tQEntry = std::max(0.01, -qB - std::sqrt(qDisc));
      real tQExit = -qB + std::sqrt(qDisc);
      real accum = 0;
      const int QSTEPS = 16;
      real qdt = (tQExit - tQEntry) / QSTEPS;
      for (int qi = 0; qi < QSTEPS; ++qi) {
        Vec3 qp = ro + rd * (tQEntry + (qi + 0.5) * qdt);
        accum += quantumField.evaluateDensity(qp) * qdt;
      }
      real alpha = std::min(1.0, accum * 5.0);
      Rgb bg = skyColor(rd);
      return {
          float(quantumField.glowColor.r * alpha * 2.0 + bg.r * (1.0 - alpha)),
          float(quantumField.glowColor.g * alpha * 2.0 + bg.g * (1.0 - alpha)),
          float(quantumField.glowColor.b * alpha * 2.0 + bg.b * (1.0 - alpha))};
    }

    Vec3 hitPos = ro + rd * tHit;
    Vec3 viewDir = rd * (-1.0);

    if (hitWater) {
      if (cameraUnderwater) {
        Rgb below = hitAlbedo;
        Rgb amb = {cachedAmbientSky.r * 0.4f, cachedAmbientSky.g * 0.55f,
                   cachedAmbientSky.b * 0.7f};
        Rgb lit = {below.r * amb.r, below.g * amb.g, below.b * amb.b};
        Vec3 trans = water.beerLambertTransmission(2.0 * std::max(tHit, 0.0));
        lit.r *= float(trans.x);
        lit.g *= float(trans.y);
        lit.b *= float(trans.z);
        lit.r += 0.02f;
        lit.g += 0.05f;
        lit.b += 0.08f;
        return lit;
      }

      Vec3 refrDir;
      const bool hasRefr = continuum::ContinuousWaterBody::refractRay(
          rd, normal, 1.0 / water.refractiveIndex, refrDir);
      const real cosTheta = std::clamp(-normal.dot(rd), 0.0, 1.0);
      const real F = continuum::ContinuousWaterBody::fresnelDielectric(
          cosTheta, 1.0, water.refractiveIndex);

      Rgb belowCol = {0.55f, 0.65f, 0.75f};
      if (hasRefr) {
        // Il fondo visto sott'acqua e' la STESSA superficie che si vede
        // fuori dall'acqua: stessi solidi (lastre del pavimento incluse),
        // stessa sabbia, stessa Terra con terreno e griglia, stesso shading.
        const Vec3 subOrigin = hitPos + refrDir * 1e-4;
        real tSub = 1e9;
        Vec3 nSub(0, 0, 1);
        Rgb albSub{0.5f, 0.5f, 0.5f};
        real metSub = 0.0, rouSub = 0.5;
        bool subValid = false;
        for (const auto &s : solids) {
          if (s.raySphereCull(subOrigin, refrDir))
            continue;
          real tBox;
          Vec3 nBox;
          if (s.raycast(subOrigin, refrDir, tBox, nBox) && tBox < tSub &&
              std::isfinite(tBox)) {
            tSub = tBox;
            nSub = nBox;
            albSub = s.albedo;
            metSub = s.metallic;
            rouSub = s.roughness;
            subValid = true;
          }
        }
        for (const auto &sp : spheres) {
          real tSph;
          Vec3 nSph;
          if (intersectSphere(subOrigin, refrDir, sp.pos, sp.radius, tSph,
                              nSph) &&
              tSph < tSub) {
            tSub = tSph;
            nSub = nSph;
            albSub = sp.albedo;
            metSub = sp.metallic;
            rouSub = sp.roughness;
            subValid = true;
          }
        }
        {
          real tSn;
          Vec3 nSn;
          if (sand.intersectSand(subOrigin, refrDir, tSn, nSn) && tSn < tSub) {
            tSub = tSn;
            nSub = nSn;
            albSub = {0.86f, 0.74f, 0.44f};
            metSub = 0.0;
            rouSub = 0.88;
            subValid = true;
          }
        }
        {
          real tE;
          Vec3 nE;
          real latE, lonE;
          if (intersectEarth(subOrigin, refrDir, tE, nE, latE, lonE) &&
              tE < tSub && std::isfinite(tE)) {
            auto surf = globe.terrain.sample(latE, lonE, 0.0);
            const real detail = terrainDetail(latE, lonE);
            const real shade = std::clamp(1.0 + 0.008 * detail, 0.6, 1.4);
            albSub.r = std::clamp(surf.albedo.r * float(shade), 0.0f, 1.0f);
            albSub.g = std::clamp(surf.albedo.g * float(shade), 0.0f, 1.0f);
            albSub.b = std::clamp(surf.albedo.b * float(shade), 0.0f, 1.0f);
            metSub = 0.0;
            rouSub = std::min(1.0, surf.roughness * 1.8);
            const real lw =
                0.08 + std::clamp(200.0 / std::max(1.0, tE), 0.0, 0.5);
            overlayGrid(albSub, latE, lonE, lw);
            tSub = tE;
            nSub = nE;
            subValid = true;
          }
        }
        if (subValid) {
          const Vec3 subHit = subOrigin + refrDir * tSub;
          const Rgb litSub = shadeOpaque(subHit, nSub, albSub, metSub, rouSub,
                                         refrDir * -1.0, tSub, nLights);
          const Vec3 trans =
              water.beerLambertTransmission(2.0 * std::max(tSub, 0.0));
          belowCol = {float(litSub.r * trans.x), float(litSub.g * trans.y),
                      float(litSub.b * trans.z)};
        }
      }
      const Vec3 reflDir = rd - normal * (2.0 * rd.dot(normal));
      const Rgb reflCol = skyColor(reflDir);
      Rgb specSum = {0.0f, 0.0f, 0.0f};
      for (std::size_t li = 0; li < nLights; ++li) {
        const auto &light = lighting.lights[li];
        if (!light.active)
          continue;
        const Vec3 lDir =
            (light.type == LightSource::Type::Directional)
                ? light.direction * (-1.0)
                : apartment::safeNormalize(light.position - hitPos);
        const Vec3 halfVec = apartment::safeNormalize(lDir + viewDir);
        const real nDotH = std::max(0.0, normal.dot(halfVec));
        const real spec = std::pow(nDotH, 128.0);
        const Rgb &lCol = cachedLightColors[li];
        specSum.r += float(lCol.r * spec * 2.5);
        specSum.g += float(lCol.g * spec * 2.5);
        specSum.b += float(lCol.b * spec * 2.5);
      }
      // Riva: a profondita' -> 0 il film non riflette ne' assorbe e la vista
      // deve raccordarsi in modo continuo col fondo asciutto (niente linea).
      const real filmBlend =
          waterDepth >= 0.0 ? std::clamp(waterDepth / 0.003, 0.0, 1.0) : 1.0;
      const real wb = filmBlend * filmBlend * (3.0 - 2.0 * filmBlend);
      const real Fb = F * wb;
      Rgb litWater;
      litWater.r =
          float(belowCol.r * (1.0 - Fb) + reflCol.r * Fb + specSum.r * wb);
      litWater.g =
          float(belowCol.g * (1.0 - Fb) + reflCol.g * Fb + specSum.g * wb);
      litWater.b =
          float(belowCol.b * (1.0 - Fb) + reflCol.b * Fb + specSum.b * wb);
      const real ext = effectiveScattering() * tHit;
      const real transmission = std::exp(-ext);
      const real inScatter = 1.0 - transmission;
      const Rgb haze = skyColor(rd);
      return {float(litWater.r * transmission + haze.r * inScatter),
              float(litWater.g * transmission + haze.g * inScatter),
              float(litWater.b * transmission + haze.b * inScatter)};
    }

    Rgb lit = shadeOpaque(hitPos, normal, hitAlbedo, metallic, roughness,
                          viewDir, tHit, nLights);
    if (hitQuantum) {
      const real qDens = quantumField.evaluateDensity(hitPos);
      const real qAlpha = std::min(0.5, qDens * 0.5);
      lit.r += float(quantumField.glowColor.r * qAlpha);
      lit.g += float(quantumField.glowColor.g * qAlpha);
      lit.b += float(quantumField.glowColor.b * qAlpha);
    }
    if (cameraUnderwater) {
      lit.r *= 0.55f;
      lit.g *= 0.85f;
      lit.b *= 1.00f;
      lit.r += 0.02f;
      lit.g += 0.06f;
      lit.b += 0.10f;
    }
    return lit;
  }

  Image render(int width, int height, const Vec3 &camEye = Vec3(0, -3, 1.7),
               real yaw = 0, real pitch = 0) const {
    const Vec3 f(std::sin(yaw) * std::cos(pitch),
                 std::cos(yaw) * std::cos(pitch), std::sin(pitch));
    return renderView(width, height, camEye, f, Vec3(0, 0, 1));
  }

  Image renderView(int width, int height, const Vec3 &camEye, const Vec3 &fwd,
                   const Vec3 &camUp) const {
    lastObserverPos = camEye;
    currentAltitude =
        (camEye - Vec3(0, 0, -earth::planet::R_E)).norm() - earth::planet::R_E;
    real hGeo = earth::StandardAtmosphere::geopotential(currentAltitude);
    currentDensity = globe.atmo.density(hGeo);

    if (cachedLightColors.size() != lighting.lights.size())
      refreshLightCache();

    for (const auto &sol : solids)
      sol.prepare(); // cache SDF pronte prima dei thread di rendering
    Image img(width, height);
    const Vec3 f = apartment::safeNormalize(fwd, Vec3(0, 1, 0));
    Vec3 right = f.cross(camUp);
    if (right.norm2() < 1e-12)
      right = Vec3(1, 0, 0);
    else
      right = right.normalized();
    Vec3 up = right.cross(f).normalized();
    const real th = std::tan(camera.fovY / 2.0);
    const real aspect = real(width) / real(height);
    std::atomic<int> nextY{0};
    unsigned numThreads = std::max(1u, std::thread::hardware_concurrency());
    std::vector<std::thread> workers;
    workers.reserve(numThreads);
    auto worker = [&] {
      for (int y; (y = nextY++) < height;) {
        for (int x = 0; x < width; ++x) {
          real sx = ((x + 0.5) / width * 2.0 - 1.0) * aspect * th;
          real sy = (1.0 - (y + 0.5) / height * 2.0) * th;
          Vec3 dir = apartment::safeNormalize(f + right * sx + up * sy);
          Rgb c = traceRay(camEye, dir);
          float *out = img.at(x, y);
          out[0] =
              std::clamp(std::pow(c.r / (1.0f + c.r), 1.0f / 2.2f), 0.0f, 1.0f);
          out[1] =
              std::clamp(std::pow(c.g / (1.0f + c.g), 1.0f / 2.2f), 0.0f, 1.0f);
          out[2] =
              std::clamp(std::pow(c.b / (1.0f + c.b), 1.0f / 2.2f), 0.0f, 1.0f);
        }
      }
    };
    for (unsigned t = 0; t < numThreads; ++t)
      workers.emplace_back(worker);
    for (auto &t : workers)
      t.join();
    return img;
  }

  void collideSpheresWithSolids() {
    for (auto &sp : spheres) {
      for (auto &s : solids) {
        Vec3 n;
        real pen;
        if (!s.sphereContact(sp.pos, sp.radius, n, pen))
          continue;
        const bool dyn = !s.isStatic;
        const real invS = 1.0 / sp.mass;
        const real invB = dyn ? 1.0 / s.mass : 0.0;
        const real tot0 = invS + invB;
        const Vec3 p = sp.pos - n * (sp.radius - 0.5 * pen);
        const Vec3 rB = p - s.pos;
        auto kB = [&](const Vec3 &d) {
          return dyn ? d.dot(s.applyInvInertia(rB.cross(d)).cross(rB)) : 0.0;
        };
        sp.pos = sp.pos + n * (pen * invS / tot0);
        if (dyn) {
          s.pos = s.pos - n * (pen * invB / tot0);
          if (pen * invB / tot0 > 1e-4)
            s.wake();
        }
        const Vec3 rS = n * (-sp.radius);
        const Vec3 vS = sp.vel + sp.omega.cross(rS);
        const Vec3 vB = dyn ? s.pointVelocity(p) : Vec3(0, 0, 0);
        const Vec3 vr = vS - vB;
        const real vn = vr.dot(n);
        if (vn >= 0)
          continue;
        real e = std::min(sp.restitution, s.restitution);
        if (-vn < 0.2)
          e = 0;
        const real jn = -(1.0 + e) * vn / (invS + invB + kB(n));
        sp.vel = sp.vel + n * (jn * invS);
        if (dyn) {
          if (jn * invB > 0.01)
            s.wake();
          s.applyImpulseAtPoint(n * (-jn), p);
        }
        const Vec3 vt = vr - n * vn;
        const real vts = vt.norm();
        if (vts > 1e-9) {
          const real inertiaInv = 1.0 / sp.inertia();
          const Vec3 td = vt * (1.0 / vts);
          const real kt =
              invS + invB + sp.radius * sp.radius * inertiaInv + kB(td);
          const real muS = contact::combineFriction(sp.mu_s, s.mu_s);
          const real muK = contact::combineFriction(sp.mu_k, s.mu_k);
          const real jt = contact::coulombImpulse(vts / kt, jn, muS, muK);
          const Vec3 imp = td * (-jt);
          sp.vel = sp.vel + imp * invS;
          sp.omega = sp.omega + rS.cross(imp) * inertiaInv;
          if (dyn)
            s.applyImpulseAtPoint(imp * -1.0, p);
        }
      }
    }
  }

  void collideSpheresWithSpheres() {
    for (std::size_t i = 0; i < spheres.size(); ++i)
      for (std::size_t j = i + 1; j < spheres.size(); ++j) {
        auto &A = spheres[i];
        auto &B = spheres[j];
        Vec3 d = A.pos - B.pos;
        const real dist = d.norm();
        const real minD = A.radius + B.radius;
        if (dist >= minD)
          continue;
        const Vec3 n = dist > 1e-9 ? d * (1.0 / dist) : Vec3(0, 0, 1);
        const real pen = minD - dist;
        const real invA = 1.0 / A.mass, invB = 1.0 / B.mass;
        const real tot = invA + invB;
        A.pos = A.pos + n * (pen * invA / tot);
        B.pos = B.pos - n * (pen * invB / tot);
        const Vec3 rA = n * (-A.radius), rB = n * B.radius;
        const Vec3 vr =
            (A.vel + A.omega.cross(rA)) - (B.vel + B.omega.cross(rB));
        const real vn = vr.dot(n);
        if (vn >= 0)
          continue;
        real e = std::min(A.restitution, B.restitution);
        if (-vn < 0.2)
          e = 0;
        const real jn = -(1.0 + e) * vn / tot;
        A.vel = A.vel + n * (jn * invA);
        B.vel = B.vel - n * (jn * invB);
        const Vec3 vt = vr - n * vn;
        const real vts = vt.norm();
        if (vts > 1e-9) {
          const real iA = 1.0 / A.inertia(), iB = 1.0 / B.inertia();
          const Vec3 td = vt * (1.0 / vts);
          const real kt =
              tot + A.radius * A.radius * iA + B.radius * B.radius * iB;
          const real muS = contact::combineFriction(A.mu_s, B.mu_s);
          const real muK = contact::combineFriction(A.mu_k, B.mu_k);
          const real jt = contact::coulombImpulse(vts / kt, jn, muS, muK);
          const Vec3 imp = td * (-jt);
          A.vel = A.vel + imp * invA;
          B.vel = B.vel - imp * invB;
          A.omega = A.omega + rA.cross(imp) * iA;
          B.omega = B.omega - rB.cross(imp) * iB;
        }
      }
  }

  static void prepareContact(continuum::RigidSolidElement &A,
                             continuum::RigidSolidElement &B, Contact &c) {
    const Vec3 &n = c.normal;
    const Vec3 a = std::abs(n.x) < 0.9 ? Vec3(1, 0, 0) : Vec3(0, 1, 0);
    c.t1 = n.cross(a).normalized();
    c.t2 = n.cross(c.t1);
    const real e = std::min(A.restitution, B.restitution);
    for (int k = 0; k < c.manifold.count; ++k) {
      const Vec3 &p = c.manifold.points[k];
      const Vec3 vA = A.isStatic ? Vec3(0, 0, 0) : A.pointVelocity(p);
      const Vec3 vB = B.isStatic ? Vec3(0, 0, 0) : B.pointVelocity(p);
      const real vn = (vA - vB).dot(n);
      if (vn < -0.05) {
        if (!A.isStatic)
          A.wake();
        if (!B.isStatic)
          B.wake();
      }
      c.pt[k] = Contact::Pt();
      c.pt[k].bounce = vn < -0.5 ? -e * vn : 0.0;
    }
  }

  static void solveContactPoint(continuum::RigidSolidElement &A,
                                continuum::RigidSolidElement &B, const Vec3 &p,
                                const Vec3 &n, const Vec3 &t1, const Vec3 &t2,
                                Contact::Pt &pt, real muS, real muK) {
    const bool sA = A.isStatic, sB = B.isStatic;
    if (sA && sB)
      return;
    const Vec3 rA = p - A.pos, rB = p - B.pos;
    const Vec3 zero(0, 0, 0);
    auto relVel = [&](const Vec3 &d) {
      const Vec3 vA = sA ? zero : A.pointVelocity(p);
      const Vec3 vB = sB ? zero : B.pointVelocity(p);
      return (vA - vB).dot(d);
    };
    auto kEff = [&](const Vec3 &d) {
      real k = 0;
      if (!sA)
        k += 1.0 / A.mass + d.dot(A.applyInvInertia(rA.cross(d)).cross(rA));
      if (!sB)
        k += 1.0 / B.mass + d.dot(B.applyInvInertia(rB.cross(d)).cross(rB));
      return k;
    };
    auto applyJ = [&](const Vec3 &J) {
      if (!sA) {
        A.vel = A.vel + J * (1.0 / A.mass);
        A.angVel = A.angVel + A.applyInvInertia(rA.cross(J));
      }
      if (!sB) {
        B.vel = B.vel - J * (1.0 / B.mass);
        B.angVel = B.angVel - B.applyInvInertia(rB.cross(J));
      }
    };

    const real Kn = kEff(n);
    if (Kn < 1e-12)
      return;
    real lam = (pt.bounce - relVel(n)) / Kn;
    const real nj = std::max(pt.jn + lam, 0.0);
    lam = nj - pt.jn;
    pt.jn = nj;
    applyJ(n * lam);

    real *accT[2] = {&pt.jt1, &pt.jt2};
    const Vec3 *dirT[2] = {&t1, &t2};
    for (int a = 0; a < 2; ++a) {
      const real Kt = kEff(*dirT[a]);
      if (Kt < 1e-12)
        continue;
      real nt = *accT[a] - relVel(*dirT[a]) / Kt;
      if (std::abs(nt) > muS * pt.jn)
        nt = std::copysign(muK * pt.jn, nt);
      const real l = nt - *accT[a];
      *accT[a] = nt;
      applyJ(*dirT[a] * l);
    }

    const Vec3 w = (sA ? zero : A.angVel) - (sB ? zero : B.angVel);
    const real kRot = (sA ? 0.0 : n.dot(A.applyInvInertia(n))) +
                      (sB ? 0.0 : n.dot(B.applyInvInertia(n)));
    if (kRot > 1e-12) {
      const real lim = muK * pt.jn * 0.05;
      const real l = std::clamp(-w.dot(n) / kRot, -lim, lim);
      if (!sA)
        A.angVel = A.angVel + A.applyInvInertia(n * l);
      if (!sB)
        B.angVel = B.angVel - B.applyInvInertia(n * l);
    }
  }

  // ------------------------------------------------------------------
  //  ANTI-PENETRAZIONE: i solidi non possono mai restare sovrapposti.
  // ------------------------------------------------------------------
  using GroundFn = continuum::RigidSolidElement::GroundHeightFn;

  real groundHeightAt(real x, real y) const {
    real gz = 0.0;
    const real sh = sand.sampleHeight(x, y);
    if (std::isfinite(sh) && sh > gz)
      gz = sh;
    return gz;
  }

  // Il solido `c` e' libero (nessuna sovrapposizione con altri solidi, ne'
  // sotto il terreno) con un gap di sicurezza `margin`?
  bool isSolidPlacementFree(const continuum::RigidSolidElement &c,
                            real margin = 0.003) const {
    if (c.lowestZ() < groundHeightAt(c.pos.x, c.pos.y) - 1e-6)
      return false;
    for (const auto &o : solids) {
      if ((c.pos - o.pos).norm() > c.boundRadius() + o.boundRadius() + margin)
        continue;
      Vec3 n;
      real ov;
      if (continuum::RigidSolidElement::sdfOverlap(c, o, n, ov, margin))
        return false;
    }
    return true;
  }

  // Inserisce un solido garantendo che NASCA senza compenetrazioni: se il
  // punto richiesto e' occupato (anche da un solido identico nello stesso
  // punto) cerca la posizione libera piu' vicina (prima in alto, poi
  // in anelli laterali). Restituisce l'indice del solido inserito.
  int addSolid(continuum::RigidSolidElement s) {
    s.wake();
    s.refreshWorldHalf();
    const Vec3 p0 = s.pos;
    const real step =
        std::max(0.05, 0.5 * std::min({s.size.x, s.size.y, s.size.z}));
    auto fitGround = [&](continuum::RigidSolidElement &c) {
      const real g = groundHeightAt(c.pos.x, c.pos.y);
      const real lz = c.lowestZ();
      if (lz < g)
        c.pos.z += (g - lz);
    };
    continuum::RigidSolidElement cand = s;
    bool found = false;
    for (int lift = 0; lift <= 60 && !found; ++lift) {
      for (int ring = 0; ring <= 4 && !found; ++ring) {
        const int nDir = ring == 0 ? 1 : 6 * ring;
        for (int a = 0; a < nDir && !found; ++a) {
          const real ang = 2.0 * PI * real(a) / real(nDir);
          cand = s;
          cand.pos = p0 + Vec3(std::cos(ang) * ring * step,
                               std::sin(ang) * ring * step, lift * step);
          fitGround(cand);
          if (isSolidPlacementFree(cand)) {
            found = true;
            s = cand;
          }
        }
      }
    }
    s.refreshWorldHalf();
    solids.push_back(s);
    return int(solids.size()) - 1;
  }

  // Proiezione posizionale a punto fisso: separa COMPLETAMENTE ogni coppia
  // sovrapposta (correzione piena, nessuno slop, ripartita per massa
  // inversa; i corpi statici non si muovono) e alza i corpi sotto il
  // terreno. Itera fino a che non resta nessuna penetrazione.
  void resolvePenetrations(const GroundFn &groundFn, int maxIter = 64) {
    const real skin = 1.0e-5; // gap lasciato dopo la separazione
    for (int it = 0; it < maxIter; ++it) {
      bool moved = false;
      for (std::size_t i = 0; i < solids.size(); ++i) {
        for (std::size_t j = i + 1; j < solids.size(); ++j) {
          auto &A = solids[i];
          auto &B = solids[j];
          if (A.isStatic && B.isStatic)
            continue;
          if ((A.pos - B.pos).norm() > A.boundRadius() + B.boundRadius())
            continue;
          Vec3 n;
          real depth;
          if (!continuum::RigidSolidElement::sdfOverlap(A, B, n, depth, 0.0))
            continue;
          const real invA = A.isStatic ? 0.0 : 1.0 / A.mass;
          const real invB = B.isStatic ? 0.0 : 1.0 / B.mass;
          const real invSum = invA + invB;
          if (invSum < 1e-15)
            continue;
          const real corr = depth + skin;
          const real dA = corr * invA / invSum;
          const real dB = corr * invB / invSum;
          if (!A.isStatic) {
            A.pos = A.pos + n * dA;
            if (dA > 1e-4)
              A.wake();
          }
          if (!B.isStatic) {
            B.pos = B.pos - n * dB;
            if (dB > 1e-4)
              B.wake();
          }
          moved = true;
        }
      }
      if (groundFn) {
        for (auto &s : solids) {
          if (s.isStatic)
            continue;
          const real g = groundFn(s.pos.x, s.pos.y);
          const real lz = s.lowestZ();
          if (std::isfinite(g) && lz < g) {
            s.pos.z += (g - lz);
            if (s.vel.z < 0)
              s.vel.z = 0;
            moved = true;
          }
        }
      }
      if (!moved)
        break;
    }
  }

  void stepPhysics(real dt) {
    if (dt <= 0 || !std::isfinite(dt))
      return;
    simTime += dt;
    updateEnvironment();

    water.setBedProvider([this](real x, real y) { return sampleBed(x, y); });
    water.setWind(currentWind);
    water.setGravity(currentGravity);
    bedTimer += dt;
    if (bedTimer > 0.25) {
      water.refreshBed();
      bedTimer = 0.0;
    }
    water.step(dt);

    sand.relaxAvalanche(1);
    real airDensity = currentDensity;

    // --- EM: prima azzera, poi accumula Coulomb + Lorentz ---
    emField.resetForces(solids);
    emField.applyCoulombBetweenSolids(solids);
    emField.applyToSolids(solids);

    for (auto &s : solids)
      s.refreshWorldHalf();

    real maxLinSpeed = 0.0, maxAngSpeed = 0.0, minHalf = 1.0;
    for (const auto &s : solids) {
      if (s.isStatic || s.asleep)
        continue;
      maxLinSpeed = std::max(maxLinSpeed, s.vel.norm());
      maxAngSpeed = std::max(maxAngSpeed, s.angVel.norm());
      const Vec3 he = s.halfExtents();
      minHalf = std::min({minHalf, he.x, he.y, he.z});
    }
    for (const auto &sp : spheres) {
      maxLinSpeed = std::max(maxLinSpeed, sp.vel.norm());
      maxAngSpeed = std::max(maxAngSpeed, sp.omega.norm());
      minHalf = std::min(minHalf, sp.radius);
    }
    int nSub = 1;
    {
      const real dtLinTarget =
          0.5 * std::max(minHalf, 1e-3) / std::max(maxLinSpeed, 1e-3);
      const real dtAngTarget = 0.25 / std::max(maxAngSpeed, 1e-3);
      const real dtTarget = std::min(dtLinTarget, dtAngTarget);
      if (dt > dtTarget)
        nSub = std::clamp(int(std::ceil(dt / dtTarget)), 1, 16);
    }
    const real dtSub = dt / nSub;

    std::vector<Contact> contacts;
    contacts.reserve(solids.size() * 2);

    const int SOLVER_ITERS = 16;
    const real contactMargin = 2.0e-3; // contatti "speculativi" di riposo

    GroundFn groundFn = [this](real x, real y) -> real {
      return groundHeightAt(x, y);
    };

    // Limite anti-tunneling: nessun corpo percorre piu' di meta' del proprio
    // semi-lato minimo per sotto-passo (neanche oltre il tetto di 16
    // sotto-passi).
    for (auto &s : solids) {
      if (s.isStatic || s.asleep)
        continue;
      const Vec3 he = s.halfExtents();
      const real vmax =
          0.5 * std::max(std::min({he.x, he.y, he.z}), 1e-3) / dtSub;
      const real vn = s.vel.norm();
      if (vn > vmax)
        s.vel = s.vel * (vmax / vn);
    }

    // Stato iniziale pulito: spawn / spinte esterne non devono lasciare
    // alcuna compenetrazione prima di integrare.
    resolvePenetrations(groundFn);

    for (int sub = 0; sub < nSub; ++sub) {
      for (auto &s : solids)
        s.stepDynamics(dtSub, gravityVec, water, wind, airDensity, simTime,
                       groundFn);

      contacts.clear();
      for (std::size_t i = 0; i < solids.size(); ++i) {
        for (std::size_t j = i + 1; j < solids.size(); ++j) {
          auto &A = solids[i];
          auto &B = solids[j];
          if (A.isStatic && B.isStatic)
            continue;
          if ((A.isStatic || A.asleep) && (B.isStatic || B.asleep))
            continue;
          if ((A.pos - B.pos).norm() >
              A.boundRadius() + B.boundRadius() + contactMargin)
            continue;
          Vec3 n;
          real overlap;
          if (!continuum::RigidSolidElement::sdfOverlap(A, B, n, overlap,
                                                        contactMargin))
            continue;
          Contact c;
          c.i = int(i);
          c.j = int(j);
          c.normal = n;
          c.overlap = overlap;
          c.manifold = continuum::RigidSolidElement::buildManifold(
              A, B, contactMargin, &n);
          if (c.manifold.count == 0)
            continue;
          prepareContact(A, B, c);
          contacts.push_back(c);
        }
      }

      for (int iter = 0; iter < SOLVER_ITERS; ++iter) {
        for (auto &c : contacts) {
          auto &A = solids[c.i];
          auto &B = solids[c.j];
          const real muS = contact::combineFriction(A.mu_s, B.mu_s);
          const real muK = contact::combineFriction(A.mu_k, B.mu_k);
          for (int k = 0; k < c.manifold.count; ++k)
            solveContactPoint(A, B, c.manifold.points[k], c.normal, c.t1, c.t2,
                              c.pt[k], muS, muK);
        }
      }

      // Garanzia finale del sotto-passo: zero penetrazione.
      resolvePenetrations(groundFn);

      // Sfere: stesso sotto-passo dei solidi (niente tunneling), vento
      // locale, terreno/sabbia, urti con solidi e fra sfere.
      for (auto &sp : spheres) {
        const real vmax = 0.5 * sp.radius / dtSub;
        const real vn = sp.vel.norm();
        if (vn > vmax)
          sp.vel = sp.vel * (vmax / vn);
        const Vec3 wv = wind.evaluateVelocity(sp.pos, simTime);
        sp.step(dtSub, air, currentGravity, &water, &wv, groundFn);
      }
      collideSpheresWithSolids();
      collideSpheresWithSpheres();
      collideSpheresWithSolids();
    }

    matterSim.gravity = gravityVec;
    matterSim.step(dt, air);

    for (auto &s : solids)
      s.refreshWorldHalf();
  }
