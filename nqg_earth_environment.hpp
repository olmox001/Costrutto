class TerrainGenerator {
public:
  explicit TerrainGenerator(uint32_t /*seed*/ = 1337) {}
  // FIX: rng_ inutilizzato rimosso; il seed e' solo di compatibilita'.

  real baseHeight(real lat, real lon) const {
    if (!std::isfinite(lat) || !std::isfinite(lon))
      return 0.0;
    const real sl1 = std::sin(lat * 1.7 + 0.3);
    const real cl1 = std::cos(lon * 1.1);
    const real sl2 = std::sin(lat * 3.1 + 1.2);
    const real cl2 = std::cos(lon * 2.3 + 0.5);
    const real sl3 = std::sin(lat * 5.7 + 2.1);
    const real cl3 = std::cos(lon * 4.7 + 1.7);
    const real sl4 = std::sin(lat * 11.3 + 0.7);
    const real cl4 = std::cos(lon * 9.1 + 2.5);
    const real sl5 = std::sin(lat * 23.1 + 3.3);
    const real cl5 = std::cos(lon * 17.9 + 0.9);
    real h = 900.0 * sl1 * cl1 + 450.0 * sl2 * cl2 + 180.0 * sl3 * cl3 +
             70.0 * sl4 * cl4 + 25.0 * sl5 * cl5 - 250.0;
    const real a = std::abs(lat);
    if (a > 1.20)
      h += (a - 1.20) * 1200.0;
    return h;
  }

  SurfaceSample sample(real lat, real lon, real alt) const {
    SurfaceSample s;
    s.height = baseHeight(lat, lon);
    const real a = std::abs(lat);
    // FIX: priorita' corretta per neve/ghiaccio ad alta latitudine,
    // indipendentemente dalla quota.
    if (s.height < 0.0) {
      s.type = SurfaceType::Water;
      s.roughness = 0.02;
      s.albedo = {0.05f, 0.15f, 0.42f};
    } else if (a > 1.18 || s.height > 3800.0) {
      s.type = SurfaceType::Snow;
      s.roughness = 0.12;
      s.albedo = {0.92f, 0.94f, 0.98f};
    } else if (a > 1.05) {
      s.type = SurfaceType::Ice;
      s.roughness = 0.05;
      s.albedo = {0.78f, 0.86f, 0.92f};
    } else if (s.height < 4.0) {
      s.type = SurfaceType::Sand;
      s.roughness = 0.08;
      s.albedo = {0.82f, 0.72f, 0.48f};
    } else if (s.height < 450.0) {
      s.type = SurfaceType::Grass;
      s.roughness = 0.25;
      s.albedo = {0.26f, 0.46f, 0.20f};
    } else {
      s.type = SurfaceType::Rock;
      s.roughness = 0.55;
      s.albedo = {0.44f, 0.39f, 0.34f};
    }
    s.tempC =
        30.0 - 6.5 * (s.height / 1000.0) - 50.0 * (a / PI_E) - 0.0065 * alt;
    return s;
  }
};

struct GeoPoint {
  real lat, lon, alt;
};

class EarthGlobe {
public:
  StandardAtmosphere atmo;
  GravityField grav;
  TerrainGenerator terrain;

  static void enuBasis(real lat, real lon, Vec3 &up, Vec3 &east, Vec3 &north) {
    lat = std::clamp(lat, -PI_E * 0.5, PI_E * 0.5);
    const real cl = std::cos(lat), sl = std::sin(lat);
    const real co = std::cos(lon), so = std::sin(lon);

    up = Vec3(cl * co, cl * so, sl);
    east = Vec3(-so, co, 0.0);

    const real nUp = up.norm();
    if (nUp < 1e-9)
      up = Vec3(0, 0, 1);
    else
      up = up * (1.0 / nUp);
    const real eDotU = east.dot(up);
    east = east - up * eDotU;
    const real nE = east.norm();
    if (nE < 1e-9)
      east = Vec3(1, 0, 0);
    else
      east = east * (1.0 / nE);
    north = up.cross(east);
    const real nN = north.norm();
    if (nN < 1e-9)
      north = Vec3(0, 1, 0);
    else
      north = north * (1.0 / nN);
  }

  Vec3 toECEF(const GeoPoint &g) const {
    const real r = planet::R_E + g.alt;
    const real cl = std::cos(g.lat), sl = std::sin(g.lat);
    const real co = std::cos(g.lon), so = std::sin(g.lon);
    return Vec3(r * cl * co, r * cl * so, r * sl);
  }

  static real altitudeOf(const Vec3 &p) {
    const real r = p.norm();
    if (!std::isfinite(r))
      return 0.0;
    return r - planet::R_E;
  }
  static real latitudeOf(const Vec3 &p) {
    const real r = p.norm();
    if (r < 1e-9)
      return 0.0;
    return std::asin(std::clamp(p.z / r, -1.0, 1.0));
  }
  static real longitudeOf(const Vec3 &p) { return std::atan2(p.y, p.x); }

  static Vec3 enuToECEF(const Vec3 &enu, const Vec3 &refECEF, const Vec3 &up,
                        const Vec3 &east, const Vec3 &north) {
    return refECEF + east * enu.x + north * enu.y + up * enu.z;
  }
  static Vec3 ecefToENU(const Vec3 &ecef, const Vec3 &refECEF, const Vec3 &up,
                        const Vec3 &east, const Vec3 &north) {
    const Vec3 d = ecef - refECEF;
    return Vec3(d.dot(east), d.dot(north), d.dot(up));
  }

  static void ecefToLatLon(const Vec3 &ecef, real &lat, real &lon, real &alt) {
    const real r = ecef.norm();
    if (r < 1e-9 || !std::isfinite(r)) {
      lat = 0.0;
      lon = 0.0;
      alt = -planet::R_E;
      return;
    }
    lat = std::asin(std::clamp(ecef.z / r, -1.0, 1.0));
    lon = std::atan2(ecef.y, ecef.x);
    alt = r - planet::R_E;
  }

  struct EnvSample {
    real altitude, lat, lon;
    real gravity;
    real pressure, temperature, density, soundSpeed;
    Vec3 wind;
    SurfaceSample surf;
    real coriolis;
  };

  // FIX: p deve essere in coordinate ECEF con centro del globo nell'origine.
  EnvSample sample(const Vec3 &p, const WindProfile &wp) const {
    EnvSample e;
    e.altitude = altitudeOf(p);
    e.lat = latitudeOf(p);
    e.lon = longitudeOf(p);
    e.gravity = grav.g(e.lat, e.altitude);
    e.pressure = atmo.pressure(e.altitude);
    e.temperature = atmo.temperature(e.altitude);
    e.density = atmo.density(e.altitude);
    e.soundSpeed = atmo.speedOfSound(e.altitude);
    e.surf = terrain.sample(e.lat, e.lon, e.altitude);
    e.coriolis = 2.0 * planet::omega_E * std::sin(e.lat);

    Vec3 up, east, north;
    enuBasis(e.lat, e.lon, up, east, north);
    e.wind = WindField::velocityAt(wp, e.altitude, up, east, north);
    return e;
  }
};

class GlobeResolver {
public:
  Vec3 pos = Vec3(0, 0, 1.7);
  Vec3 up = Vec3(0, 0, 1);
  Vec3 fwd = Vec3(0, 1, 0);
  real traveled = 0.0;
  long turns = 0;

  static Vec3 center() { return Vec3(0, 0, -planet::R_E); }
  static real closureAngle() { return 2.0 * PI_E; }
  static real closureArc() { return closureAngle() * planet::R_E; }

  Vec3 right() const { return fwd.cross(up); }
  real altitude() const { return (pos - center()).norm() - planet::R_E; }
  real revolutionFraction() const { return traveled / closureAngle(); }

  static Vec3 rodrigues(const Vec3 &v, const Vec3 &k, real a) {
    const real c = std::cos(a), s = std::sin(a);
    return v * c + k.cross(v) * s + k * (k.dot(v) * (1.0 - c));
  }

  void turn(real dYaw) {
    fwd = (fwd * std::cos(dYaw) + right() * std::sin(dYaw));
    orthonormalize();
  }

  void walk(const Vec3 &tangent, real dAlt) {
    const Vec3 r = pos - center();
    const real rho = r.norm();
    const Vec3 d = tangent - up * tangent.dot(up);
    const real dist = d.norm();
    Vec3 u1 = up;
    if (dist > 1e-12) {
      const real a = dist / rho;
      const Vec3 dh = d * (1.0 / dist);
      u1 = up * std::cos(a) + dh * std::sin(a);
      fwd = rodrigues(fwd, up.cross(dh), a);
      advance(a);
    }
    up = u1;
    pos = center() + u1 * (rho + dAlt);
    orthonormalize();
  }

  void setPosition(const Vec3 &p) {
    const Vec3 r = p - center();
    const real rho = r.norm();
    if (rho < 1e-9) {
      pos = p;
      return;
    }
    const Vec3 u1 = r * (1.0 / rho);
    const Vec3 k = up.cross(u1);
    const real sn = k.norm();
    if (sn > 1e-15) {
      const real a = std::atan2(sn, std::clamp(up.dot(u1), -1.0, 1.0));
      fwd = rodrigues(fwd, k * (1.0 / sn), a);
      advance(a);
    }
    up = u1;
    pos = p;
    orthonormalize();
    snapClosure();
  }

private:
  void advance(real a) {
    traveled += a;
    while (traveled >= closureAngle()) {
      traveled -= closureAngle();
      ++turns;
    }
  }

  void orthonormalize() {
    up = up.normalized();
    Vec3 f = fwd - up * fwd.dot(up);
    if (f.norm2() < 1e-18)
      f = std::abs(up.x) < 0.9 ? Vec3(1, 0, 0).cross(up)
                               : Vec3(0, 1, 0).cross(up);
    fwd = f.normalized();
  }

  void snapClosure() {
    const Vec3 home(0, 0, 1);
    if (turns > 0 && std::acos(std::clamp(up.dot(home), -1.0, 1.0)) < 1e-7 &&
        traveled < 1e-6) {
      pos = center() + home * (pos - center()).norm();
      up = home;
      orthonormalize();
    }
  }
};

